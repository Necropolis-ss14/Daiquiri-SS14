                                    string.Equals(_chessGameStatus, "started", StringComparison.OrdinalIgnoreCase);
        ChessDrawButton.Visible = ChessResignButton.Visible;
        ChessAbortButton.Visible = inProgress;

        UpdateChessClockLabels();
    }

    /// <summary>
    /// Small result banner shown for a few seconds when a game reaches a terminal state.
    /// It is intentionally non-interactive so it cannot swallow a click on the board.
    /// </summary>
    private void ShowChessResultPopup(ChessGameState state)
    {
        var key = $"{state.GameId}|{state.Status}|{state.Winner}";
        if (string.Equals(_chessResultPopupKey, key, StringComparison.Ordinal))
            return;

        _chessResultPopupKey = key;

        var won = !string.IsNullOrEmpty(state.Winner) &&
                  !string.Equals(state.Winner, "draw", StringComparison.OrdinalIgnoreCase) &&
                  string.Equals(state.Winner, _chessMyColor, StringComparison.OrdinalIgnoreCase);

        var title = "Партия завершена";
        var text = string.IsNullOrWhiteSpace(state.StatusText)
            ? "Результат партии объявлен."
            : state.StatusText;
        var color = Color.FromHex("#FFE9A8");

        switch (state.Status)
        {
            case "mate":
                title = won ? "Победа" : "Поражение";
                text = won ? "Мат. Соперник получил мат." : "Мат. Вам поставили мат.";
                color = Color.FromHex(won ? "#8FD16A" : "#E06C75");
                break;
            case "resign":
                title = won ? "Победа" : "Поражение";
                text = won ? "Соперник сдался." : "Вы сдались.";
                color = Color.FromHex(won ? "#8FD16A" : "#E06C75");
                break;
            case "timeout":
            case "outoftime":
                title = won ? "Победа" : "Поражение";
                text = won ? "У соперника истекло время." : "У вас истекло время.";
                color = Color.FromHex(won ? "#8FD16A" : "#E06C75");
                break;
            case "stalemate":
                title = "Ничья";
                text = "Пат. У соперника нет допустимых ходов.";
                color = Color.FromHex("#C7B8A8");
                break;
            case "draw":
                title = "Ничья";
                text = "Партия завершилась вничью.";
                color = Color.FromHex("#C7B8A8");
                break;
            case "variantDraw":
                title = "Ничья";
                text = "Ничья по правилам варианта.";
                color = Color.FromHex("#C7B8A8");
                break;
            case "variantWin":
                title = won ? "Победа" : "Поражение";
                text = "Партия завершена по правилам варианта.";
                color = Color.FromHex(won ? "#8FD16A" : "#E06C75");
                break;
            case "aborted":
                title = "Партия отменена";
                text = "Партия не была доиграна.";
                color = Color.FromHex("#C7B8A8");
                break;
            case "noStart":
                title = "Партия не началась";
                text = "Соперник не сделал первый ход.";
                color = Color.FromHex("#C7B8A8");
                break;
            case "cheat":
                title = "Партия завершена";
                text = "Зафиксировано нарушение правил.";
                color = Color.FromHex("#E06C75");
                break;
        }

        PlayChessResultSound(state.Status, won);

        ChessResultTitle.Text = title;
        ChessResultTitle.FontColorOverride = color;
        ChessResultText.Text = WrapChessText(text);
        ChessResultPopupHost.Visible = true;

        var generation = ++_chessResultPopupGeneration;
        Robust.Shared.Timing.Timer.Spawn(TimeSpan.FromSeconds(4), () =>
        {
            if (generation != _chessResultPopupGeneration || !IsInsideTree)
                return;

            ChessResultPopupHost.Visible = false;
        });
    }

    private void HideChessResultPopup()
    {
        _chessResultPopupGeneration++;
        ChessResultPopupHost.Visible = false;
    }

    private void ResetChessClocks(int whiteMs, int blackMs)
    {
        _chessWhiteBaseMs = Math.Max(0, whiteMs);
        _chessBlackBaseMs = Math.Max(0, blackMs);
        _chessClockBase = _timing.CurTime;
        var generation = ++_chessClockGeneration;

        UpdateChessClockLabels();

        // Correspondence games have no clock at all: never start a countdown.
        if (!_chessUnlimited &&
            string.Equals(_chessGameStatus, "started", StringComparison.OrdinalIgnoreCase))
        {
            ScheduleChessClockTick(generation);
        }
    }

    private void ScheduleChessClockTick(int generation)
    {
        Robust.Shared.Timing.Timer.Spawn(
            TimeSpan.FromMilliseconds(250),
            () => TickChessClocks(generation));
    }

    private void TickChessClocks(int generation)
    {
        if (generation != _chessClockGeneration)
            return;

        UpdateChessClockLabels();

        if (!_chessUnlimited &&
            string.Equals(_chessGameStatus, "started", StringComparison.OrdinalIgnoreCase))
        {
            ScheduleChessClockTick(generation);
        }
    }

    private void UpdateChessClockLabels()
    {
        var myColor = string.IsNullOrEmpty(_chessMyColor) ? "white" : _chessMyColor;
        var bottomIsWhite = !string.Equals(myColor, "black", StringComparison.OrdinalIgnoreCase);

        var whiteMs = _chessWhiteBaseMs;
        var blackMs = _chessBlackBaseMs;

        if (!_chessUnlimited &&
            string.Equals(_chessGameStatus, "started", StringComparison.OrdinalIgnoreCase))
        {
            var elapsed = (int) Math.Max(0, (_timing.CurTime - _chessClockBase).TotalMilliseconds);
            if (string.Equals(_chessTurn, "white", StringComparison.OrdinalIgnoreCase))
                whiteMs = Math.Max(0, whiteMs - elapsed);
            else
                blackMs = Math.Max(0, blackMs - elapsed);
        }

        var bottomMs = bottomIsWhite ? whiteMs : blackMs;
        var topMs = bottomIsWhite ? blackMs : whiteMs;

        ChessPlayerClockLabel.Text = _chessUnlimited ? "∞" : FormatChessClock(bottomMs);
        ChessOpponentClockLabel.Text = _chessUnlimited ? "∞" : FormatChessClock(topMs);

        var bottomTurn = bottomIsWhite
            ? string.Equals(_chessTurn, "white", StringComparison.OrdinalIgnoreCase)
            : string.Equals(_chessTurn, "black", StringComparison.OrdinalIgnoreCase);

        ChessPlayerClockLabel.FontColorOverride = bottomTurn && _chessGameActive
            ? Color.FromHex("#FFD479")
            : Color.FromHex("#C7B8A8");
        ChessOpponentClockLabel.FontColorOverride = !bottomTurn && _chessGameActive
            ? Color.FromHex("#FFD479")
            : Color.FromHex("#C7B8A8");
    }

    private void ApplyChessModeHighlight(Button button, int minutes, int increment)
    {
        var selected = _chessMinutes == minutes && _chessIncrement == increment;
        button.Modulate = selected ? Color.FromHex("#FFD479") : Color.White;
    }

    private static string FormatChessClock(int milliseconds)
    {
        if (milliseconds <= 0)
            return "0:00";

        var totalSeconds = milliseconds / 1000;
        if (totalSeconds >= 3600)
        {
            var hours = totalSeconds / 3600;
            var minutes = totalSeconds % 3600 / 60;
            var seconds = totalSeconds % 60;
            return $"{hours}:{minutes:00}:{seconds:00}";
        }

        return $"{totalSeconds / 60}:{totalSeconds % 60:00}";
    }

    public void OnChessLinkStartReceived(ChessLinkStartState state)
    {
        // A start state can be cached by the UI system and replayed when the PDA is
        // reopened. Only the answer to the current click may start a browser flow.
        if (string.IsNullOrEmpty(state.RequestId) ||
            !string.Equals(state.RequestId, _chessLinkRequestId, StringComparison.Ordinal))
        {
            return;
        }

        if (!ChessPage.Visible || !_chessLinkPending)
        {
            _chessLinkRequestId = string.Empty;
            _boundUi?.SendMessage(new CartridgeUiMessage(
                new ChessUiMessageEvent(ChessUiAction.CancelLink)));
            return;
        }

        if (!string.IsNullOrEmpty(state.Error))
        {
            _chessLinkPending = false;
            _chessLinkRequestId = string.Empty;
            ShowChessStatus(state.Error, true);
            UpdateChessAccountButton();
            return;
        }

        if (!TryParseAbsoluteUri(state.AuthUrl, out var authUri) ||
            authUri.Scheme != Uri.UriSchemeHttps ||
            (authUri.Host != "lichess.org" && authUri.Host != "lichess.dev") ||
            !TryParseAbsoluteUri(state.RedirectUri, out var redirectUri) ||
            redirectUri.Scheme != Uri.UriSchemeHttp ||
            redirectUri.Host != "127.0.0.1" ||
            redirectUri.Port <= 0 ||
            !redirectUri.IsLoopback)
        {
            _chessLinkPending = false;
            _chessLinkRequestId = string.Empty;
            ShowChessStatus("Сервер вернул некорректный адрес привязки Lichess.", true);
            _boundUi?.SendMessage(new CartridgeUiMessage(
                new ChessUiMessageEvent(ChessUiAction.CancelLink)));
            UpdateChessAccountButton();
            return;
        }

        var authQuery = ParseQuery(authUri.Query);
        authQuery.TryGetValue("state", out var authState);
        _chessLinkState = authState ?? string.Empty;

        if (string.IsNullOrEmpty(_chessLinkState))
        {
            _chessLinkPending = false;
            _chessLinkRequestId = string.Empty;
            ShowChessStatus("Сервер вернул некорректный адрес привязки Lichess.", true);
            _boundUi?.SendMessage(new CartridgeUiMessage(
                new ChessUiMessageEvent(ChessUiAction.CancelLink)));
            UpdateChessAccountButton();
            return;
        }

        _uriOpener.OpenUri(authUri);

        // The server also listens on the loopback redirect for local clients. If that
        // succeeds, a status update arrives and hides this panel. Remote players can
        // paste the redirect URL from the browser's address bar instead.
        ChessLinkFinishPanel.Visible = true;
        ChessLinkCallbackInput.Text = string.Empty;
        ChessLinkFinishButton.Disabled = false;
        ChessLinkCallbackInput.GrabKeyboardFocus();

        ShowChessStatus(
            "Открыл Lichess в браузере. Войдите и разрешите доступ.\n" +
            "Затем скопируйте адрес страницы, на которую вас перенаправило, и вставьте его ниже.",
            false);

        UpdateChessAccountButton();
        ScheduleChessLinkTimeout(state.TimeoutSeconds);
    }

    private void OnChessLinkFinishPressed()
    {
        if (!_chessLinkPending || !ChessPage.Visible)
            return;

        if (!TryParseChessCallback(
                ChessLinkCallbackInput.Text,
                out var code,
                out var callbackState,
                out var error,
                out var errorDescription))
        {
            ShowChessStatus(
                "Вставьте адрес страницы после входа в Lichess или сам код авторизации.",
                true);
            return;
        }

        if (string.IsNullOrEmpty(callbackState))
            callbackState = _chessLinkState;

        if (string.IsNullOrEmpty(callbackState))
        {
            ShowChessStatus("Не удалось определить состояние авторизации. Начните привязку заново.", true);
            return;
        }

        if (string.IsNullOrEmpty(code) && string.IsNullOrEmpty(error))
        {
            ShowChessStatus("Вставьте адрес страницы после входа в Lichess.", true);
            return;
        }

        ChessLinkFinishButton.Disabled = true;
        ChessLinkCallbackInput.Text = string.Empty;
        ShowChessStatus("Проверяю аккаунт Lichess...", false);

        _boundUi?.SendMessage(new CartridgeUiMessage(
            new ChessUiMessageEvent(
                ChessUiAction.CompleteLink,
                code,
                callbackState,
                error,
                errorDescription)));
    }

