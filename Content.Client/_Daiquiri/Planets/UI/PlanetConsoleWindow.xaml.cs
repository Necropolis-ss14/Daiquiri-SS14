using Content.Client.UserInterface.Controls;
using Content.Shared._Daiquiri.Planets;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Daiquiri.Planets.UI;

[GenerateTypedNameReferences]
public sealed partial class PlanetConsoleWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototype = default!;

    [Dependency] private IEntitySystemManager _sysMan = default!;

    private static readonly ResPath HeaderIconRsi = new("/Textures/Structures/Machines/computers.rsi");
    private static readonly ResPath HeaderScreenRsi = new("/Textures/_Daiquiri/Structures/Machines/computers.rsi");

    private const float PrintedFlashTime = 4f;
    private static readonly Color SubtitleColor = Color.FromHex("#9FB0BB");
    private static readonly Color BlockedColor = Color.FromHex("#FF7A7A");

    public event Action<string>? OnPrint;

    private readonly List<PlanetCard> _cards = new();
    private string _planetList = string.Empty;
    private string _printing = string.Empty;
    private float _duration;
    private float _remaining;
    private float _cooldown;
    private float _cooldownDuration;
    private float _printedFlash;
    private string _blockReason = string.Empty;

    public PlanetConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var sprites = _sysMan.GetEntitySystem<SpriteSystem>();
        HeaderIcon.Texture = sprites.Frame0(new SpriteSpecifier.Rsi(HeaderIconRsi, "computer"));

        HeaderScreen.Texture = sprites.Frame0(new SpriteSpecifier.Rsi(HeaderScreenRsi, "planet"));

        HeaderSubtitle.SetMessage(Loc.GetString("planet-console-window-subtitle"), SubtitleColor);
        StatusLabel.Text = Loc.GetString("planet-console-status-idle");

        HintLabel.Text = Loc.GetString("planet-console-hint-cooldown");
        HintLabel.FontColorOverride = SubtitleColor;
    }

    public void UpdateState(PlanetConsoleState state)
    {
        SyncCards(state.Planets);

        if (_printing != string.Empty && state.Printing == string.Empty)
            _printedFlash = PrintedFlashTime;

        _printing = state.Printing;
        _duration = state.PrintDuration;
        _remaining = state.PrintRemaining;
        _cooldown = state.CooldownRemaining;
        _cooldownDuration = state.CooldownDuration;
        _blockReason = state.BlockReason;

        var blocked = _printing != string.Empty || _cooldown > 0f || _blockReason != string.Empty;

        foreach (var card in _cards)
        {
            card.SetState(card.PlanetId == _printing, blocked);
        }

        RefreshStatus();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var changed = false;

        if (_printedFlash > 0f)
        {
            _printedFlash = MathF.Max(0f, _printedFlash - args.DeltaSeconds);
            changed = true;
        }

        if (_printing != string.Empty)
        {
            if (_remaining > 0f)
            {
                _remaining = MathF.Max(0f, _remaining - args.DeltaSeconds);
                changed = true;
            }
        }
        else if (_cooldown > 0f)
        {
            _cooldown = MathF.Max(0f, _cooldown - args.DeltaSeconds);
            changed = true;

            if (_cooldown <= 0f)
                UnblockCards();
        }

        if (changed)
            RefreshStatus();
    }

    private void UnblockCards()
    {
        if (_blockReason != string.Empty)
            return;

        foreach (var card in _cards)
        {
            card.SetState(false, false);
        }
    }

    private void SyncCards(List<string> planets)
    {
        var key = string.Join(",", planets);
        if (key == _planetList)
            return;

        _planetList = key;
        PlanetList.RemoveAllChildren();
        _cards.Clear();

        foreach (var id in planets)
        {
            if (!_prototype.TryIndex<PlanetDestinationPrototype>(id, out var planet))
                continue;

            var card = new PlanetCard(planet);
            card.PrintPressed += planetId => OnPrint?.Invoke(planetId);
            _cards.Add(card);
            PlanetList.AddChild(card);
        }
    }

    private void RefreshStatus()
    {
        if (_printing != string.Empty)
        {
            var name = _prototype.TryIndex<PlanetDestinationPrototype>(_printing, out var planet)
                ? Loc.GetString(planet.Name)
                : _printing;

            StatusLabel.FontColorOverride = null;
            StatusLabel.Text = Loc.GetString("planet-console-status-printing",
                ("planet", name),
                ("time", MathF.Ceiling(_remaining)));

            PrintProgress.Visible = true;
            PrintProgress.Value = _duration <= 0f
                ? 0f
                : Math.Clamp((_duration - _remaining) / _duration, 0f, 1f);

            return;
        }

        PrintProgress.Visible = false;

        if (_printedFlash > 0f)
        {
            StatusLabel.FontColorOverride = null;
            StatusLabel.Text = Loc.GetString("planet-console-status-printed");
            return;
        }

        if (_blockReason != string.Empty)
        {
            StatusLabel.FontColorOverride = BlockedColor;
            StatusLabel.Text = Loc.GetString(_blockReason);
            return;
        }

        if (_cooldown > 0f)
        {
            StatusLabel.FontColorOverride = null;
            StatusLabel.Text = Loc.GetString("planet-console-status-cooldown", ("time", FormatTime(_cooldown)));

            PrintProgress.Visible = true;
            PrintProgress.Value = _cooldownDuration <= 0f
                ? 0f
                : Math.Clamp(1f - _cooldown / _cooldownDuration, 0f, 1f);

            return;
        }

        StatusLabel.FontColorOverride = null;
        StatusLabel.Text = Loc.GetString("planet-console-status-idle");
    }

    private static string FormatTime(float seconds)
    {
        var total = (int) MathF.Ceiling(seconds);
        return $"{total / 60:00}:{total % 60:00}";
    }
}