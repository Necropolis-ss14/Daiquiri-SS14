using Content.Client.UserInterface.Controls;
using Robust.Client.UserInterface.Controls;
using Content.Shared._Daiquiri.PaperPlease;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;

namespace Content.Client._Daiquiri.PaperPlease;

[GenerateTypedNameReferences]
public sealed partial class PassportWindow : FancyWindow
{
    public PassportWindow()
    {
        RobustXamlLoader.Load(this);

        HeaderPanel.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#c62828") };
        BodyPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#1b1b1f"),
            BorderColor = Color.FromHex("#ffffff22"),
            BorderThickness = new Thickness(1),
        };
        PhotoPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#2a2a30"),
            BorderColor = Color.FromHex("#ffffff44"),
            BorderThickness = new Thickness(1),
        };
    }

    public void Update(PassportUiState state)
    {
        StateLabel.Text = state.StateName.ToUpperInvariant();
        HeaderPanel.PanelOverride = new StyleBoxFlat { BackgroundColor = state.StateColor };
        OwnerLabel.Text = Loc.GetString("passport-ui-owner", ("name", state.OwnerName));
        SeriesLabel.Text = Loc.GetString("passport-ui-series", ("series", state.Series), ("number", state.Number));
        CityLabel.Text = Loc.GetString("passport-ui-city", ("city", state.IssueCity));
        IssueLabel.Text = Loc.GetString("passport-ui-issued", ("year", state.IssueYear));
        ExpiryLabel.Text = Loc.GetString("passport-ui-expires", ("year", state.ExpiryYear));

        var entMan = IoCManager.Resolve<IEntityManager>();
        SignatureLabel.Visible = state.HasSignature;

        StampsContainer.RemoveAllChildren();
        foreach (var stamp in state.Stamps)
        {
            var panel = new PanelContainer { Margin = new Thickness(0, 2, 0, 0) };
            panel.PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#00000000"),
                BorderColor = stamp.Color,
                BorderThickness = new Thickness(2),
            };
            var label = new Label { Text = stamp.Name, HorizontalAlignment = HAlignment.Center };
            label.ModulateSelfOverride = stamp.Color;
            panel.AddChild(label);
            StampsContainer.AddChild(panel);
        }
        SignatureLabel.Text = Loc.GetString("passport-ui-signature-markup", ("name", state.OwnerName));

        if (state.Owner is { } owner && entMan.TryGetEntity(owner, out var ownerUid))
            Photo.SetEntity(ownerUid);
        else
            Photo.SetEntity(null);
    }
}
