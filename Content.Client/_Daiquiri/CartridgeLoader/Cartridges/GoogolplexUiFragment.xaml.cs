    private void RenderChessBoard()
    {
        if (_chessBoard.Length != 64)
            _chessBoard = ChessStartBoard;

        var legalTargets = new HashSet<int>();
        foreach (var move in _chessLegalMoves)
            legalTargets.Add(move.To);

        for (var displayRow = 0; displayRow < 8; displayRow++)
        {
            for (var displayCol = 0; displayCol < 8; displayCol++)
            {
                var index = DisplayToBoardIndex(displayRow, displayCol);

                var piece = _chessBoard[index];
                var texture = piece == '.'
                    ? null
                    : GetChessPieceTexture(ChessPieceNames.GetValueOrDefault(piece));

                var button = _chessCells[displayRow, displayCol];
                button.Texture = texture;

                if (index == _chessSelectedIndex)
                    button.Modulate = Color.FromHex("#FFE9A8");
                else if (IsChessLastMoveSquare(index))
                    button.Modulate = Color.FromHex("#BFE3A0");
                else
                    button.Modulate = Color.White;

                // While dragging, fade the piece on its origin square so it does not look
                // like there are two of it.
                if (_chessDragging && index == _chessDragFrom)
                    button.Modulate = new Color(1f, 1f, 1f, 0.25f);

                var dot = _chessDots[displayRow, displayCol];
                var showDot = legalTargets.Contains(index);
                dot.Visible = showDot;
                if (showDot)
                {
                    dot.Texture = piece == '.'
                        ? GetChessDotTexture()
                        : GetChessRingTexture();
                    dot.Modulate = Color.White;
                }
            }
        }
    }

    private int DisplayToBoardIndex(int displayRow, int displayCol)
    {
        return ChessBoardFlipped
            ? (7 - displayRow) * 8 + (7 - displayCol)
            : displayRow * 8 + displayCol;
    }

    private void PlayChessMoveSound(string previousBoard, string lastMove, string status)
    {
        if (lastMove.Length < 4 || previousBoard.Length != 64)
            return;

        var from = SquareToIndex(lastMove[..2]);
        var to = SquareToIndex(lastMove.Substring(2, 2));
        if (from is < 0 or >= 64 || to is < 0 or >= 64)
            return;

        var moving = previousBoard[from];
        var captured = previousBoard[to] != '.';
        // En passant captures land on an empty square; the captured pawn is beside it.
        if (char.ToLowerInvariant(moving) == 'p' && from % 8 != to % 8 && previousBoard[to] == '.')
            captured = true;

        var path = lastMove.Length >= 5
            ? "/Audio/Effects/chime.ogg"
            : captured
                ? "/Audio/Effects/Footsteps/largethud.ogg"
                : $"/Audio/Effects/Footsteps/wood{Random.Shared.Next(1, 6)}.ogg";

        var volume = lastMove.Length >= 5 ? -2f : captured ? -4f : -6f;
        _chessAudio.PlayGlobal(
            new SoundPathSpecifier(path),
            Filter.Local(),
            false,
            AudioParams.Default.WithVolume(volume));

        if (string.Equals(status, "started", StringComparison.OrdinalIgnoreCase) &&
            _chessPosition != null &&
            _chessPosition.IsKingAttacked(_chessPosition.WhiteToMove))
        {
            _chessAudio.PlayGlobal(
                new SoundPathSpecifier("/Audio/Effects/alert.ogg"),
                Filter.Local(),
                false,
                AudioParams.Default.WithVolume(-7f));
        }
    }

