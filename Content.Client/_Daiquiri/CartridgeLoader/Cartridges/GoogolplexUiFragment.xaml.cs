    private void OnChessAccountPressed()
    {
        if (_chessLinkStatusLoading || _chessLinkPending)
            return;

        if (!_chessLinkConfigured)
        {
            ShowChessStatus("Привязка Lichess не настроена на сервере.", true);
            return;
        }

        if (_chessLinkLinked && !_chessLinkTokenExpired)
        {
            ShowChessStatus($"Аккаунт Lichess уже привязан: {_chessLinkUsername}.", false);
            return;
        }

        _chessLinkPending = true;
        _chessLinkRequestId = Guid.NewGuid().ToString("N");
        UpdateChessAccountButton();
        ShowChessStatus("Открываю Lichess. Завершите вход в браузере.", false);

        _boundUi?.SendMessage(new CartridgeUiMessage(
            new ChessUiMessageEvent(ChessUiAction.StartLink, requestId: _chessLinkRequestId)));
    }

    private void OnChessUnlinkPressed()
    {
        if (_chessLinkStatusLoading || _chessLinkPending || !_chessLinkLinked)
            return;

        // Two clicks: the second one actually removes the link, so a misclick cannot log
        // the player out in the middle of a game.
        if (!_chessUnlinkConfirm)
        {
            _chessUnlinkConfirm = true;
            _chessUnlinkConfirmGeneration++;
            var generation = _chessUnlinkConfirmGeneration;
            UpdateChessAccountButton();
            ShowChessStatus("Нажмите «Выйти из Lichess» ещё раз, чтобы отвязать аккаунт.", false);

            Robust.Shared.Timing.Timer.Spawn(TimeSpan.FromSeconds(4), () =>
            {
                if (_chessUnlinkConfirmGeneration != generation)
                    return;

                _chessUnlinkConfirm = false;
                UpdateChessAccountButton();
            });

            return;
        }

        _chessUnlinkConfirm = false;
        _chessUnlinkConfirmGeneration++;
        UpdateChessAccountButton();
        ShowChessStatus("Отвязываю аккаунт Lichess...", false);

        SendChessMessage(new ChessUiMessageEvent(ChessUiAction.UnlinkAccount));
    }

    public void OnChessLinkStatusReceived(ChessLinkStatusState state)
    {
        _chessLinkStatusLoading = false;
        _chessLinkStatusKnown = true;
        _chessLinkStatusGeneration++;
        _chessLinkPending = false;
        _chessLinkRequestId = string.Empty;
        _chessLinkState = string.Empty;
        _chessLinkTimeoutGeneration++;
        _chessUnlinkConfirm = false;
        _chessUnlinkConfirmGeneration++;
        HideChessLinkFinishPanel();
        var wasLinked = _chessLinkLinked;
        _chessLinkConfigured = state.Configured;
        _chessLinkLinked = state.Linked;
        _chessLinkTokenExpired = state.TokenExpired;
        _chessLinkUsername = state.Username;
        _chessPlayerName = state.Username;
        _chessBlocked = state.Blocked;
        _chessAccessBroken = state.AccessBroken;
        _chessBlockReason = state.BlockReason ?? string.Empty;
        _chessBlockedMinutesLeft = state.BlockedMinutesLeft;

        if (!string.IsNullOrEmpty(state.Error))
        {
            ShowChessStatus(state.Error, true);
        }
        else if (state.AccessBroken)
        {
            ShowChessStatus(
                string.IsNullOrEmpty(_chessBlockReason)
                    ? "Lichess не принимает доступ к аккаунту. Привяжите аккаунт заново."
                    : _chessBlockReason,
                true);
        }
        else if (state.Blocked)
        {
            var minutes = state.BlockedMinutesLeft > 0
                ? $" Осталось примерно {state.BlockedMinutesLeft} мин."
                : string.Empty;
            ShowChessStatus(
                (string.IsNullOrEmpty(_chessBlockReason)
                    ? "Lichess временно запретил игру на этом аккаунте."
                    : _chessBlockReason) + minutes,
                true);
        }
        else if (state.Linked)
        {
            ShowChessStatus(
                state.TokenExpired
                    ? $"Аккаунт Lichess: {state.Username}. Требуется повторная авторизация."
                    : $"Аккаунт Lichess привязан: {state.Username}.",
                false);
        }
        else if (wasLinked)
        {
            ShowChessStatus("Аккаунт Lichess отвязан.", false);
        }
        else
        {
            ChessStatusLabel.Visible = false;
        }

        UpdateChessAccountButton();
        UpdateChessGamePanel();

        if (_chessLinkLinked && !_chessLinkTokenExpired)
            RequestChessGameState();
    }

