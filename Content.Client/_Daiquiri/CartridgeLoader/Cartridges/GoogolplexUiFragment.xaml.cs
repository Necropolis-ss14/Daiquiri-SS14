    /// <summary>
    /// If the server does not answer the status request (for example because the cartridge
    /// was re-attached after reopening the PDA), retry once and then leave the loading
    /// state instead of showing "Проверка аккаунта..." forever.
    /// </summary>
    private void ScheduleChessLinkStatusRetry()
    {
        var generation = ++_chessLinkStatusGeneration;

        Robust.Shared.Timing.Timer.Spawn(TimeSpan.FromSeconds(2), () =>
        {
            if (generation != _chessLinkStatusGeneration || !_chessLinkStatusLoading)
                return;

            RequestChessLinkStatus();
            RequestChessGameState();

            Robust.Shared.Timing.Timer.Spawn(TimeSpan.FromSeconds(3), () =>
            {
                if (generation != _chessLinkStatusGeneration || !_chessLinkStatusLoading)
                    return;

                // A status snapshot or a game snapshot already arrived: the connection is
                // alive and the current message (for example a Lichess play-ban reason)
                // must not be replaced by a generic "no status" error.
                if (_chessLinkStatusKnown)
                {
                    _chessLinkStatusLoading = false;
                    UpdateChessAccountButton();
                    return;
                }

                _chessLinkStatusLoading = false;
                UpdateChessAccountButton();
                ShowChessStatus(
                    "Не удалось получить статус аккаунта Lichess. Откройте сайт заново.",
                    true);
            });
        });
    }

