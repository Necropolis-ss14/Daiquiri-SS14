    /// <summary>
    /// Accepts a challenge another Lichess player sent to this account. The server waits
    /// for the gameStart event, so the game subsite opens as soon as the board is known.
    /// </summary>
    private void AcceptChessChallenge()
    {
        if (_chessChallengeId.Length == 0 || ChessGameInProgress)
            return;

        var challengeId = _chessChallengeId;
        _chessChallengeId = string.Empty;
        _chessGameSearching = true;
        ResetChessGameView(
            "starting",
            $"Принимаем вызов от {_chessChallenger}...",
            _chessChallengeTimeControl,
            ChessTimeControlMinutes(_chessChallengeTimeControl));
        _chessAutoOpenedGameKey = "search";
        SendChessMessage(new ChessUiMessageEvent(ChessUiAction.AcceptChallenge, challengeId: challengeId));
        UpdateChessGamePanel();
        ShowChessGamePage();
    }

    private void DeclineChessChallenge()
    {
        if (_chessChallengeId.Length == 0)
            return;

        var challengeId = _chessChallengeId;
        _chessChallengeId = string.Empty;
        _chessChallenger = string.Empty;
        SendChessMessage(new ChessUiMessageEvent(ChessUiAction.DeclineChallenge, challengeId: challengeId));
