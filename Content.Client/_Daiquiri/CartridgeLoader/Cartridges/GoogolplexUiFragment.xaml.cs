    private void OnSendPressed(BaseButton.ButtonEventArgs args)
    {
        var text = StarWayMessageInput.Text?.Trim();
        if (string.IsNullOrWhiteSpace(text) || string.IsNullOrEmpty(_currentStarWayBoardCode))
            return;

        // One post per 30 seconds. Clicking while the cooldown is running must explain the
        // rule and show the exact time left instead of silently dropping the message.
        var now = _timing.CurTime;
        if (now < _nextPostAllowed)
        {
            ShowPostCooldown(sent: false);
            return;
        }

        var author = "Аноним";
        if (!StarWayAnonymousCheck.Pressed)
        {
            var customName = StarWayNameInput.Text?.Trim();
            if (!string.IsNullOrWhiteSpace(customName))
                author = customName;
        }

        SendStarWayMessage(_currentStarWayBoardCode, author, text);
        StarWayMessageInput.Text = "";
        StarWayMessageInput.GrabKeyboardFocus();

        _nextPostAllowed = now + PostCooldown;
        ShowPostCooldown(sent: true);
    }

    private void ShowPostCooldown(bool sent)
    {
        var remaining = _nextPostAllowed - _timing.CurTime;
        if (remaining <= TimeSpan.Zero)
        {
            StarWayCooldownLabel.Visible = false;
            return;
        }

        var seconds = (int)Math.Ceiling(remaining.TotalSeconds);
        StarWayCooldownLabel.FontColorOverride = Color.FromHex(sent ? "#2A6A2A" : "#A02020");
        StarWayCooldownLabel.Text = sent
            ? $"Отправлено. Следующее через {seconds} с."
            : $"Раз в 30 сек. Осталось: {seconds} с.";
        StarWayCooldownLabel.Visible = true;

        // Single ticking chain: a new click bumps the generation so old timers die out.
        var generation = ++_cooldownGeneration;
        Robust.Shared.Timing.Timer.Spawn(TimeSpan.FromMilliseconds(250), () => TickPostCooldown(generation));
    }

    private void TickPostCooldown(int generation)
    {
        if (generation != _cooldownGeneration)
            return;

        var remaining = _nextPostAllowed - _timing.CurTime;
        if (remaining <= TimeSpan.Zero)
        {
            StarWayCooldownLabel.Visible = false;
            return;
        }

        var seconds = (int)Math.Ceiling(remaining.TotalSeconds);
        StarWayCooldownLabel.Text = $"Раз в 30 сек. Осталось: {seconds} с.";
        Robust.Shared.Timing.Timer.Spawn(TimeSpan.FromMilliseconds(250), () => TickPostCooldown(generation));
    }

