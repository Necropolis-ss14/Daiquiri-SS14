    private void ShowResultsPage(string query)
    {
        SearchPanel.Visible = false;
        Tabs.Visible = false;
        Wordmark.Visible = false;
        TopSpacer.Visible = false;
        BottomSpacer.Visible = false;
        StarWayPage.Visible = false;
        SitesPage.Visible = false;
        ErrorPage.Visible = false;
        ResultsPage.Visible = true;

        SetAddress($"googolplex.nt/search/{query}");

        _lastResultsQuery = query;

        StartSearchLoading();
        StartProgressBar(onComplete: () =>
        {
            StopSearchLoading();
            RenderResults(query);
        });
    }

    private void RenderResults(string query)
    {
        ResultsList.RemoveAllChildren();

        var normalized = NormalizeQuery(query);
        var isStarWay = IsStarWayQuery(normalized);
        _sawmill.Info($"RenderResults: query='{query}', normalized='{normalized}', isStarWay={isStarWay}");

        if (isStarWay)
        {
            AddResult("starway.nt", "StarWay", "StarWay", "Форум StarWay — обсуждения, новости, медиа, сообщество.",
                _starIcon, ShowStarWayPage);
        }

        // Every thread and subthread is indexed as its own search result.
        foreach (var entry in _threadIndex)
        {
            if (!isStarWay && !ThreadMatches(entry, query))
                continue;

            AddThreadResult(entry);
        }
    }

    /// <summary>
    /// Keyword search over a thread's title, description and post texts: any word of two or
    /// more characters matching is enough to surface the thread.
    /// </summary>
    private static bool ThreadMatches(StarWayThreadEntry entry, string query)
    {
        var words = query.ToLowerInvariant()
            .Replace("ё", "е")
            .Split(new[] { ' ', '\t', ',', '.', '/', '\\', '-', '_', '!', '?' }, StringSplitOptions.RemoveEmptyEntries);

        foreach (var word in words)
        {
            if (word.Length < 2)
                continue;

            if (entry.SearchText.Contains(word))
                return true;
        }

        return false;
    }

    private void AddThreadResult(StarWayThreadEntry entry)
    {
        var path = entry.ThreadId > 0
            ? $"t/{entry.BoardCode.ToLowerInvariant()}/{entry.ThreadId}"
            : $"t/{entry.BoardCode.ToLowerInvariant()}";

        var description = $"{PostCountText(entry.PostCount)} · /{entry.BoardCode.ToLowerInvariant()}/" +
                          (entry.IsSubthread ? " · подтред" : "");

        var code = entry.BoardCode;
        var id = entry.ThreadId;
        AddResult("starway.nt", "StarWay", entry.Title, description, _starIcon, () =>
        {
            ShowStarWayPage();
            OpenStarWayThread(code, id);
        }, path);
    }

    private static string PostCountText(int count)
    {
        if (count % 100 is >= 11 and <= 14)
            return $"{count} сообщений";

        return (count % 10) switch
        {
            1 => $"{count} сообщение",
            2 or 3 or 4 => $"{count} сообщения",
            _ => $"{count} сообщений",
        };
    }

