    private void OnChessBoardPointerDown(ScreenCoordinates position)
    {
        var local = GetChessBoardLocalPosition(position);
        var display = PositionToDisplay(local);
        if (display < 0)
            return;

        var index = DisplayToBoardIndex(display / 8, display % 8);

        // A release outside the board does not reach PointerUp; clear the drag so the
        // floating piece cannot get stuck.
        if (_chessDragging)
        {
            _chessDragging = false;
            _chessDragWasSelected = false;
            _chessDragFrom = -1;
            HideChessDragPiece();
        }

        if (!CanChessMove())
        {
            ClearChessSelection();
            return;
        }

        // Completing a click-click move: the second click lands on a highlighted square.
        if (_chessSelectedIndex >= 0 && _chessSelectedIndex != index &&
            TryFindChessMove(_chessSelectedIndex, index, out var move))
        {
            MakeChessMove(move);
            return;
        }

        var piece = _chessBoard[index];
        if (piece != '.' && IsMyChessPiece(piece))
        {
            // Clicking an already selected piece must still start a drag: otherwise the
            // first click selects it and the following drag is swallowed as a "cancel".
            _chessDragWasSelected = _chessSelectedIndex == index;
            _chessSelectedIndex = index;
            _chessLegalMoves.Clear();

            if (GetChessPosition() is { } chessPosition)
                _chessLegalMoves.AddRange(chessPosition.GetLegalMovesFrom(index));

            _chessDragging = true;
            _chessDragFrom = index;
            ShowChessDragPiece(index, GetChessBoardHostPosition(position));
            RenderChessBoard();
            return;
        }

        ClearChessSelection();
    }

    private void OnChessBoardPointerMove(ScreenCoordinates position)
    {
        if (!_chessDragging)
            return;

        ShowChessDragPiece(_chessDragFrom, GetChessBoardHostPosition(position));
    }

    private void OnChessBoardPointerUp(ScreenCoordinates position)
    {
        if (!_chessDragging)
            return;

        var from = _chessDragFrom;
        var wasSelected = _chessDragWasSelected;
        _chessDragging = false;
        _chessDragWasSelected = false;
        _chessDragFrom = -1;
        HideChessDragPiece();

        var local = GetChessBoardLocalPosition(position);
        var display = PositionToDisplay(local);
        if (display < 0)
        {
            RenderChessBoard();
            return;
        }

        var index = DisplayToBoardIndex(display / 8, display % 8);
        if (index == from)
        {
            // A plain click keeps the piece selected for click-click play. Clicking the
            // same already-selected piece without dragging still cancels the selection.
            if (wasSelected)
                ClearChessSelection();
            else
                RenderChessBoard();
            return;
        }

        // A drag is only committed when the piece is actually dropped on the green
        // move circle, not merely somewhere inside the destination square.
        if (!IsChessDotRelease(local, display / 8, display % 8))
        {
            RenderChessBoard();
            return;
        }

        if (TryFindChessMove(from, index, out var move))
        {
            MakeChessMove(move);
            return;
        }

        RenderChessBoard();
    }

    /// <summary>
    /// Converts a screen position into virtual pixels relative to the board grid. Using
    /// the grid as the reference avoids any offset between the transparent input overlay
    /// and the actual squares.
    /// </summary>
