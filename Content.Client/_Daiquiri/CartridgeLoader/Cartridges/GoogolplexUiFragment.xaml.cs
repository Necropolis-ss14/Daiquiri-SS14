/// <summary>
/// Transparent input layer that covers the whole chess board. Pointer positions are
/// reported in board-local coordinates, so click-click and drag-and-drop use the same
/// square math and the decorative piece buttons never steal the input.
/// </summary>
public sealed class ChessBoardInputControl : Control
{
    public event Action<ScreenCoordinates>? PointerDown;
    public event Action<ScreenCoordinates>? PointerUp;
    public event Action<ScreenCoordinates>? PointerMove;

    public ChessBoardInputControl()
    {
        MouseFilter = MouseFilterMode.Stop;
    }

    protected override void KeyBindDown(GUIBoundKeyEventArgs args)
    {
        if (args.Function != EngineKeyFunctions.UIClick)
        {
            base.KeyBindDown(args);
            return;
        }

        PointerDown?.Invoke(args.PointerLocation);
        args.Handle();
    }

    protected override void KeyBindUp(GUIBoundKeyEventArgs args)
    {
        if (args.Function != EngineKeyFunctions.UIClick)
        {
            base.KeyBindUp(args);
            return;
        }

        PointerUp?.Invoke(args.PointerLocation);
        args.Handle();
    }

    protected override void MouseMove(GUIMouseMoveEventArgs args)
    {
        PointerMove?.Invoke(args.GlobalPixelPosition);
        base.MouseMove(args);
    }
}
