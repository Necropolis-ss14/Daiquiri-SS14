    }

    private bool ChessGameInProgress =>
        _chessGameSearching ||
        (_chessGameActive && !IsChessFinishedStatus(_chessGameStatus));

    private static bool IsChessFinishedStatus(string status)
    {
        return status is "mate" or "resign" or "stalemate" or "timeout" or "outoftime" or "draw"
            or "aborted" or "noStart" or "cheat" or "unknown" or "variantWin" or "variantDraw"
            or "error";
    }

    private void UpdateChessGamePanel()
    {
        // A game belongs to the PDA, not to the account: someone who is not linked can
        // still open the same cartridge loader and finish a match that is already running.
        // Page visibility (chess.nt/ vs chess.nt/game) is owned by navigation, so this
        // method only toggles the parts of the lobby that depend on the account state.
        var finished = IsChessFinishedStatus(_chessGameStatus);
        var inProgress = _chessGameSearching || (_chessGameActive && !finished);
        var blocked = _chessBlocked || _chessAccessBroken;
        var canUseAccount = _chessLinkLinked && !_chessLinkTokenExpired && !inProgress;

        // A Lichess play ban only blocks the public search; inviting a friend by nick
        // still works, so keep that button available while the account is linked.
        var canStart = canUseAccount && !blocked;

        ChessGamePanel.Visible = inProgress || (_chessLinkLinked && !_chessLinkTokenExpired);

        ChessModeGrid.Visible = canStart;
        ChessModeHintLabel.Visible = canStart;
        ChessSeekButton.Visible = canStart;
        ChessFriendButton.Visible = canUseAccount;
        ChessBotButton.Visible = canUseAccount;
        ChessOpenGameButton.Visible = inProgress;

        UpdateChessBotPanel();

        var hasChallenge = _chessChallengeId.Length > 0 && !inProgress;
        ChessChallengePanel.Visible = hasChallenge;
        if (hasChallenge)
        {
            var ratedText = _chessChallengeRated ? "рейтинговая" : "без рейтинга";
            var colorText = _chessChallengeColor switch
            {
                "white" => "вы играете белыми",
                "black" => "вы играете чёрными",
                _ => "цвет случайный",
            };

            var time = string.IsNullOrEmpty(_chessChallengeTimeControl)
                ? "контроль по умолчанию"
                : _chessChallengeTimeControl;

            ChessChallengeLabel.Text = WrapChessText(
                $"Вызов от {_chessChallenger}: {time}, {ratedText}, {colorText}.");
        }

        ApplyChessModeHighlight(ChessModeBullet1Plus0, 1, 0);
        ApplyChessModeHighlight(ChessModeBullet2Plus1, 2, 1);
        ApplyChessModeHighlight(ChessModeBlitz3Plus2, 3, 2);
        ApplyChessModeHighlight(ChessModeBlitz5Plus0, 5, 0);
        ApplyChessModeHighlight(ChessModeRapid10Plus0, 10, 0);
        ApplyChessModeHighlight(ChessModeRapid15Plus10, 15, 10);
        ApplyChessModeHighlight(ChessModeClassical20Plus0, 20, 0);
        ApplyChessModeHighlight(ChessModeClassical30Plus0, 30, 0);

        var statusText = _chessGameStatusText;
        if (blocked && !inProgress)
        {
            statusText = string.IsNullOrEmpty(_chessBlockReason)
                ? "Игра на этом аккаунте сейчас недоступна."
                : _chessBlockReason;
        }
        else if (string.IsNullOrEmpty(statusText))
        {
            statusText = _chessGameSearching
                ? "Ищем соперника на Lichess..."
                : "Выберите режим и найдите соперника.";
        }

        ChessGameStatusLabel.Text = WrapChessText(statusText);
        ChessGameStatusLabel.Visible = true;

        if (_chessGameActive && !string.IsNullOrEmpty(_chessMyColor))
        {
            var myTime = string.Equals(_chessMyColor, "white", StringComparison.OrdinalIgnoreCase)
                ? _chessWhiteMs
                : _chessBlackMs;
            var theirTime = string.Equals(_chessMyColor, "white", StringComparison.OrdinalIgnoreCase)
                ? _chessBlackMs
                : _chessWhiteMs;

            var ownerPrefix = _chessDelegated && !string.IsNullOrEmpty(_chessOwnerName)
                ? $"Партия игрока {_chessOwnerName} · "
                : string.Empty;

            var clocks = _chessUnlimited
                ? "∞"
                : $"{FormatChessClock(myTime)} / {FormatChessClock(theirTime)}";

            ChessGameInfoLabel.Text = ownerPrefix + $"Партия идёт · {clocks}";
            ChessGameInfoLabel.Visible = true;
        }
        else
        {
            ChessGameInfoLabel.Visible = false;
        }
    }

