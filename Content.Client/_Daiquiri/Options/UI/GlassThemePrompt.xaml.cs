using System.Collections.Generic;
using System.Linq;
using Content.Shared._Starlight.CCVar;
using Content.Shared._Starlight.UserInterface;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;

namespace Content.Client._Daiquiri.Options.UI;

/// <summary>
/// First-run prompt: page 1 offers the liquid glass theme with a live preview,
/// page 2 (Next button) offers the interface theme. No close cross — finish with Done.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GlassThemePrompt : DefaultWindow
{
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IPrototypeManager _protoMan = default!;

    private readonly List<string> _themeIds = new();

    // Daiquiri: set when finished via Done — anything else (e.g. ESC) reopens.
    private bool _finished;

    public GlassThemePrompt()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        // Daiquiri: no close cross and no ESC dismissal — finish with Done.
        FindControl<TextureButton>("CloseButton").Visible = false;
        OnClose += () =>
        {
            if (!_finished)
                OpenCentered();
        };

        GlassCheckBox.Pressed = _cfg.GetCVar(StarlightCCVars.UIGlassTheme);
        GlassCheckBox.OnToggled += args =>
        {
            _cfg.SetCVar(StarlightCCVars.UIGlassTheme, args.Pressed);
            GlassOptions.Visible = args.Pressed;
        };
        GlassOptions.Visible = GlassCheckBox.Pressed;
        TransparencyCheckBox.Pressed = _cfg.GetCVar(StarlightCCVars.UIGlassTransparencyEnabled);
        TransparencyCheckBox.OnToggled += args =>
        {
            _cfg.SetCVar(StarlightCCVars.UIGlassTransparencyEnabled, args.Pressed);
            TransparencySlider.Visible = args.Pressed;
        };
        TransparencySlider.Slider.MinValue = 0;
        TransparencySlider.Slider.MaxValue = 100;
        TransparencySlider.Slider.SetValueWithoutEvent(_cfg.GetCVar(StarlightCCVars.UIGlassTransparency));
        TransparencySlider.ValueLabel.Text = $"{_cfg.GetCVar(StarlightCCVars.UIGlassTransparency)}%";
        TransparencySlider.Slider.OnValueChanged += args =>
        {
            var value = (int) args.Value;
            _cfg.SetCVar(StarlightCCVars.UIGlassTransparency, value);
            TransparencySlider.ValueLabel.Text = $"{value}%";
        };
        TransparencySlider.Visible = TransparencyCheckBox.Pressed;
        AccentCheckBox.Pressed = _cfg.GetCVar(StarlightCCVars.UIGlassAccentEnabled);
        AccentCheckBox.OnToggled += args =>
        {
            _cfg.SetCVar(StarlightCCVars.UIGlassAccentEnabled, args.Pressed);
            AccentSlider.Visible = args.Pressed;
        };
        AccentSlider.Slider.Color = Color.FromHex(_cfg.GetCVar(StarlightCCVars.UIGlassAccent));
        AccentSlider.Slider.OnColorChanged += color => _cfg.SetCVar(StarlightCCVars.UIGlassAccent, color.ToHex());
        AccentSlider.Visible = AccentCheckBox.Pressed;
        // Daiquiri: page 2 — interface theme picker.
        foreach (var theme in _protoMan.EnumeratePrototypes<StyleThemePrototype>().OrderBy(t => t.Order))
        {
            ThemeDropDown.Button.AddItem(Loc.GetString(theme.Name), _themeIds.Count);
            _themeIds.Add(theme.ID);
        }
        ThemeDropDown.Button.Select(Math.Max(0, _themeIds.IndexOf(_cfg.GetCVar(StarlightCCVars.StyleTheme))));
        ThemeDropDown.Button.OnItemSelected += args =>
        {
            ThemeDropDown.Button.SelectId(args.Id);
            if (args.Id >= 0 && args.Id < _themeIds.Count)
                _cfg.SetCVar(StarlightCCVars.StyleTheme, _themeIds[args.Id]);
        };

        // Daiquiri: page 2 — custom theme accent.
        StyleCustomAccentCheckBox.Pressed = _cfg.GetCVar(StarlightCCVars.StyleCustomAccent);
        StyleCustomAccentCheckBox.OnToggled += args =>
        {
            _cfg.SetCVar(StarlightCCVars.StyleCustomAccent, args.Pressed);
            StyleAccentSlider.Visible = args.Pressed;
        };
        StyleAccentSlider.Slider.Color = Color.FromHex(_cfg.GetCVar(StarlightCCVars.StyleAccent));
        StyleAccentSlider.Slider.OnColorChanged += color => _cfg.SetCVar(StarlightCCVars.StyleAccent, color.ToHex());
        StyleAccentSlider.Visible = StyleCustomAccentCheckBox.Pressed;
        NextButton.OnPressed += _ =>
        {
            ThemePage.Visible = false;
            GlassPage.Visible = true;
        };
        DoneButton.OnPressed += _ =>
        {
            _cfg.SetCVar(StarlightCCVars.UIGlassThemeSeen, true);
            _finished = true;
            Close();
        };
        BackButton.OnPressed += _ =>
        {
            GlassPage.Visible = false;
            ThemePage.Visible = true;
        };
    }
}
