using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Daiquiri.AIHelp.UI;

[GenerateTypedNameReferences]
public sealed partial class AIHelpWindow : DefaultWindow
{
    private const string UserColor = "#9ad6ff";
    private const string AiColor = "#c9a0ff";
    private const string SystemColor = "#ff6b6b";

    public event Action<string> OnMessageSend = delegate { };
    public event Action OnClear = delegate { };
    public event Action OnOpenAdminLog = delegate { };

    public AIHelpWindow()
    {
        RobustXamlLoader.Load(this);

        MinSize = new Vector2(600, 400);

        Conversation.OnMessageSubmitted += text => OnMessageSend.Invoke(text);
        ClearButton.OnPressed += _ => OnClear.Invoke();
        AdminLogButton.OnPressed += _ => OnOpenAdminLog.Invoke();
    }

    public void SetAdmin(bool isAdmin)
        => AdminLogButton.Visible = isAdmin;

    public void AddMessage(string text, bool isUser, bool isError = false)
    {
        var tag = isUser
            ? Loc.GetString("ai-help-tag-you")
            : isError
                ? Loc.GetString("ai-help-tag-system")
                : Loc.GetString("ai-help-tag-ai");

        var color = isUser ? UserColor : isError ? SystemColor : AiColor;

        var formatted = new FormattedMessage();
        formatted.AddMarkupOrThrow($"[color={color}][bold]{FormattedMessage.EscapeText(tag)}[/bold][/color]: ");
        formatted.AddText(text);

        Conversation.AddMessage(formatted);
    }

    public void SetTyping(string text)
        => Conversation.SetTyping(text);

    public void ClearMessages()
        => Conversation.ClearMessages();
}
