        CloseSubthreadCreator();
        SetAddress($"starway.nt/t/{code.ToLowerInvariant()}{(threadId > 0 ? "/" + threadId : "/")}");

        var back = CreateStarWayLink("Назад к доскам", BuildStarWayIndex);
        back.Margin = new Thickness(0, 30, 0, 8);
        StarWayContent.AddChild(back);

        StarWayContent.AddChild(new Label
        {
            Text = threadId == 0 ? $"/{board.Code.ToLowerInvariant()}/ - {board.Name}" : board.Name,
            FontOverride = _pixelFont,
            FontColorOverride = Color.Black,
            HorizontalAlignment = HAlignment.Left,
            Margin = new Thickness(0, 0, 0, 6),
        });

        var description = CreateWrappedText(board.Description, Color.FromHex("#5A4A1A"));
        description.Margin = new Thickness(0, 0, 0, 12);
        StarWayContent.AddChild(description);

        // Request this thread from the server; the reply rebuilds the content with the
        // authoritative title, post list and subthread links.
        RequestStarWayThread(code, threadId);

        // Show composer
        StarWayComposer.Visible = true;
        SetupStarWayComposer();
    }

    private RichTextLabel CreateWrappedText(string text, Color color, Font? font = null)
    {
        var label = new RichTextLabel
        {
            HorizontalAlignment = HAlignment.Left,
            VerticalAlignment = VAlignment.Top,
            HorizontalExpand = true,
        };

        label.Stylesheet = new Stylesheet(new[]
        {
            new StyleRule(
                new SelectorElement(typeof(RichTextLabel), null, null, null),
                new StyleProperty[]
                {
                    new StyleProperty("font", font ?? _textFont),
                    new StyleProperty("font-color", color),
                }),
        });

        label.SetMessage(text, color);
        return label;
    }

    private void StartProgressBar(Action? onComplete = null)
    {
        _progressCts?.Cancel();
        _progressCts = new CancellationTokenSource();
        var token = _progressCts.Token;

        SearchProgress.Visible = true;
        SearchProgress.Value = 0;
        SearchProgress.MaxValue = 100;

        Robust.Shared.Timing.Timer.Spawn(TimeSpan.FromMilliseconds(30), async () =>
        {
            try
            {
                for (int i = 0; i <= 100; i++)
                {
                    if (token.IsCancellationRequested)
                        return;

                    SearchProgress.Value = i;
                    await Task.Delay(30, token);
                }

                SearchProgress.Visible = false;
                onComplete?.Invoke();
            }
            catch (OperationCanceledException) { }
        });
    }

    private static string NormalizeQuery(string query)
    {
        return query.ToLowerInvariant()
            .Replace("ё", "е")
            .Replace(" ", "");
    }

    private static bool IsStarWayQuery(string normalized)
    {
        return normalized.Contains("starway") || normalized.StartsWith("starw") || normalized == "star" || normalized.Contains("старвей") || normalized.StartsWith("стар");
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            _progressCts?.Cancel();
            _progressCts?.Dispose();

            if (_boundUi is PdaBoundUserInterface pda)
                pda.ProgramAddressEntered -= OnProgramAddressEntered;
        }
        base.Dispose(disposing);
    }
