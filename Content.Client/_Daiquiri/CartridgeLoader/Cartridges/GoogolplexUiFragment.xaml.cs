    /// <summary>
    /// Shows the "Переход..." window with an animated dot count for 1.5 seconds on every
    /// navigation. The target page is switched immediately underneath the overlay.
    /// </summary>
    private void PlayTransition()
    {
        if (!_uiReady)
            return;

        _transitionDots = 1;
        TransitionLabel.Text = "Переход.";
        TransitionOverlay.Visible = true;

        var generation = ++_transitionGeneration;
        Robust.Shared.Timing.Timer.Spawn(TimeSpan.FromMilliseconds(300), () => TickTransition(generation));
        Robust.Shared.Timing.Timer.Spawn(TimeSpan.FromSeconds(1.5), () => EndTransition(generation));
    }

    private void TickTransition(int generation)
    {
        if (generation != _transitionGeneration || !TransitionOverlay.Visible)
            return;

        _transitionDots = _transitionDots % 3 + 1;
        TransitionLabel.Text = "Переход" + new string('.', _transitionDots);

        Robust.Shared.Timing.Timer.Spawn(TimeSpan.FromMilliseconds(300), () => TickTransition(generation));
    }

    private void EndTransition(int generation)
    {
        if (generation != _transitionGeneration)
            return;

        TransitionOverlay.Visible = false;
    }

    public void SetBoundUi(BoundUserInterface boundUi)
    {
        _boundUi = boundUi;
        _sawmill.Info($"SetBoundUi: {boundUi.GetType().Name}, address='{_currentAddress}'");

        if (boundUi is PdaBoundUserInterface pda)
        {
            pda.ProgramAddressEntered += OnProgramAddressEntered;
            pda.SetProgramAddressBar(_currentAddress);
        }

        RequestThreadIndex();

        // Reopening the PDA creates a new fragment. Restore the last visited page after the
        // BUI has finished attaching this fragment, otherwise the first request can race
        // the cartridge activation and the page stays in its loading state.
        Robust.Shared.Timing.Timer.Spawn(TimeSpan.FromMilliseconds(50), RestoreLastPage);
    }

    private void RestoreLastPage()
    {
        if (!_uiReady || _boundUi == null)
            return;

        if (_lastAddress.StartsWith("chess.nt/friend", StringComparison.OrdinalIgnoreCase))
        {
            ShowChessFriendPage();
            return;
        }

        if (_lastAddress.StartsWith("chess.nt/bot", StringComparison.OrdinalIgnoreCase))
        {
            ShowChessBotPage();
            return;
        }

        if (_lastAddress.StartsWith("chess.nt", StringComparison.OrdinalIgnoreCase))
        {
            ShowChessPage();
            return;
        }

        if (_lastAddress.StartsWith("starway.nt", StringComparison.OrdinalIgnoreCase))
        {
            NavigateTo(_lastAddress);
            return;
        }

        if (_lastAddress.StartsWith("googolplex.nt/search/", StringComparison.OrdinalIgnoreCase))
        {
            NavigateTo(_lastAddress);
            return;
        }

        ShowSearchPage();
    }

    private void RequestThreadIndex()
    {
        _boundUi?.SendMessage(new CartridgeUiMessage(new StarWayUiMessageEvent(StarWayUiAction.ListThreads)));
    }

    public void OnThreadIndexReceived(StarWayThreadIndexState state)
    {
        _threadIndex = state.Threads ?? new List<StarWayThreadEntry>();

        if (ResultsPage.Visible && _lastResultsQuery != null && !SearchProgress.Visible)
            RenderResults(_lastResultsQuery);
    }

    private void OnProgramAddressEntered(string text)
    {
        var url = text?.Trim();
        if (!string.IsNullOrEmpty(url))
            NavigateTo(url);
    }

    private void OnSearchPressed(BaseButton.ButtonEventArgs e)
    {
        ExecuteSearch();
    }

    private void ExecuteSearch()
    {
        var query = SearchBox.Text?.Trim() ?? "";
        _sawmill.Info($"Search requested: '{query}'");
        if (string.IsNullOrEmpty(query))
            return;

        ShowResultsPage(query);
    }

    private void SetAddress(string url)
    {
        var leftChess = _currentAddress.StartsWith("chess.nt", StringComparison.OrdinalIgnoreCase) &&
                        !url.StartsWith("chess.nt", StringComparison.OrdinalIgnoreCase);

        _currentAddress = url;

        // The initial ShowSearchPage() during fragment construction must not erase the page
        // remembered from the previous PDA session.
        if (!_restoringPage)
            _lastAddress = url;

        if (leftChess)
            CancelChessSearchIfPending();

        if (_boundUi is PdaBoundUserInterface pda)
            pda.SetProgramAddressBar(url);
    }

    /// <summary>
    /// Stops a search that has not found an opponent yet. A match that is already running is
    /// left alone: it belongs to the PDA and can be continued or handed to another player.
    /// </summary>
    private void CancelChessSearchIfPending()
    {
        if (!_chessGameSearching || !string.IsNullOrEmpty(_chessGameId))
            return;

        SendChessMessage(new ChessUiMessageEvent(ChessUiAction.CancelSeek));
        _chessGameSearching = false;
        _chessGameActive = false;
        _chessGameStatus = "idle";
        _chessGameStatusText = string.Empty;
        _chessAutoOpenedGameKey = string.Empty;
    }

    /// <summary>
    /// Browser-style navigation from the address bar. Known virtual URLs open the matching
    /// page; anything else is treated as a Googolplex query.
    /// </summary>
    private void NavigateTo(string raw, string notFoundMessage = "Сайт не найден")
    {
        var text = raw.Trim();
        var lower = text.ToLowerInvariant();

        if (lower.StartsWith("https://"))
        {
            text = text[8..];
            lower = lower[8..];
        }
        else if (lower.StartsWith("http://"))
        {
            text = text[7..];
            lower = lower[7..];
        }

        var cut = lower.IndexOfAny(new[] { '?', '#' });
        if (cut >= 0)
        {
            text = text[..cut];
            lower = lower[..cut];
        }

        while (lower.EndsWith('/'))
        {
            text = text[..^1];
            lower = lower[..^1];
        }

        switch (lower)
        {
            case "googolplex.nt":
            case "googolplex.nt/search":
                ShowSearchPage();
                return;
            case "googolplex.nt/sites":
                ShowSitesPage();
                return;
            case "starway.nt":
                ShowStarWayPage();
                return;
            case "chess.nt/friend":
                ShowChessFriendPage();
                return;
            case "chess.nt/bot":
                ShowChessBotPage();
                return;
            case "chess.nt":
            case "chess.nt/game":
            case "chess.nt/play":
                ShowChessPage();
                return;
        }

        const string searchPrefix = "googolplex.nt/search/";
        if (lower.StartsWith(searchPrefix))
        {
            var query = text[searchPrefix.Length..].Trim();
            ShowSearchPage();
            if (query.Length > 0)
            {
                SearchBox.Text = query;
                ShowResultsPage(query);
            }

            return;
        }

        const string threadPrefix = "starway.nt/t/";
        if (lower.StartsWith(threadPrefix))
        {
            var rest = text[threadPrefix.Length..];
            var parts = rest.Split('/', StringSplitOptions.RemoveEmptyEntries);
            var code = parts.Length > 0 ? FindStarWayBoardCode(parts[0]) : null;
            if (code != null)
            {
                var threadId = 0;
                if (parts.Length > 1)
                    int.TryParse(parts[1], out threadId);

                ShowStarWayPage();
                OpenStarWayThread(code, threadId);
                return;
            }
        }

        // Unknown address: full-screen error page.
        ShowErrorPage(text, notFoundMessage);
    }

