    private bool IsChessDotRelease(Vector2 local, int displayRow, int displayCol)
    {
        var size = ChessBoardGrid.Size;
        var cellWidth = size.X > 0 ? size.X / 8f : ChessCellSize;
        var cellHeight = size.Y > 0 ? size.Y / 8f : ChessCellSize;
        var center = new Vector2(
            (displayCol + 0.5f) * cellWidth,
            (displayRow + 0.5f) * cellHeight);

        // Scale the visual dot radius with the board, then allow a couple of pixels of
        // tolerance so the drop does not require pixel-perfect aim.
        var radius = MathF.Min(cellWidth, cellHeight) * (ChessDotSize / (2f * ChessCellSize)) + 2f;
        return Vector2.DistanceSquared(local, center) <= radius * radius;
    }

    private bool TryFindChessMove(int from, int to, out ChessMove move)
    {
        foreach (var candidate in _chessLegalMoves)
        {
            if (candidate.From == from && candidate.To == to)
            {
                move = candidate;
                return true;
            }
        }

        move = default;
        return false;
    }

