    /// <summary>
    /// Keyword search over a thread's title, description and post texts: any word of two or
    /// more characters matching is enough to surface the thread.
    /// </summary>
    private static bool ThreadMatches(StarWayThreadEntry entry, string query)
    {
        var words = query.ToLowerInvariant()
            .Replace("ё", "е")
            .Split(new[] { ' ', '\t', ',', '.', '/', '\\', '-', '_', '!', '?' }, StringSplitOptions.RemoveEmptyEntries);

        foreach (var word in words)
        {
            if (word.Length < 2)
                continue;

            if (entry.SearchText.Contains(word))
                return true;
        }

        return false;
    }

    private void AddThreadResult(StarWayThreadEntry entry)
    {
        var path = entry.ThreadId > 0
            ? $"t/{entry.BoardCode.ToLowerInvariant()}/{entry.ThreadId}"
            : $"t/{entry.BoardCode.ToLowerInvariant()}";

        var description = $"{PostCountText(entry.PostCount)} · /{entry.BoardCode.ToLowerInvariant()}/" +
                          (entry.IsSubthread ? " · подтред" : "");

        var code = entry.BoardCode;
        var id = entry.ThreadId;
        AddResult("starway.nt", "StarWay", entry.Title, description, _starIcon, () =>
        {
            ShowStarWayPage();
            OpenStarWayThread(code, id);
        }, path);
    }

    private static string PostCountText(int count)
    {
        if (count % 100 is >= 11 and <= 14)
            return $"{count} сообщений";

        return (count % 10) switch
        {
            1 => $"{count} сообщение",
            2 or 3 or 4 => $"{count} сообщения",
            _ => $"{count} сообщений",
        };
    }

