    private static Dictionary<string, string> ParseQuery(string query)
    {
        var result = new Dictionary<string, string>(StringComparer.Ordinal);

        if (query.StartsWith('?'))
            query = query[1..];

        foreach (var pair in query.Split('&', StringSplitOptions.RemoveEmptyEntries))
        {
            var separator = pair.IndexOf('=');
            var key = separator >= 0 ? pair[..separator] : pair;
            var value = separator >= 0 ? pair[(separator + 1)..] : string.Empty;

            result[Uri.UnescapeDataString(key.Replace('+', ' '))] =
                Uri.UnescapeDataString(value.Replace('+', ' '));
        }

        return result;
    }

    /// <summary>
    /// Parses an absolute URI without touching <c>System.UriKind</c>, which is not part of the
    /// content sandbox whitelist.
    /// </summary>
    private static bool TryParseAbsoluteUri(string value, out Uri uri)
    {
        uri = null!;

        if (string.IsNullOrWhiteSpace(value))
            return false;

        try
        {
            var parsed = new Uri(value);
            if (!parsed.IsAbsoluteUri)
                return false;

            uri = parsed;
            return true;
        }
        catch (Exception)
        {
            return false;
        }
    }

    private static bool TryParseChessCallback(
        string input,
        out string code,
        out string state,
        out string error,
        out string errorDescription)
    {
        code = string.Empty;
        state = string.Empty;
        error = string.Empty;
        errorDescription = string.Empty;

        input = input.Trim();
        if (string.IsNullOrEmpty(input))
            return false;

        if (TryParseAbsoluteUri(input, out var uri))
        {
            var query = ParseQuery(uri.Query);
            query.TryGetValue("code", out var codeVal);
            query.TryGetValue("state", out var stateVal);
            query.TryGetValue("error", out var errorVal);
            query.TryGetValue("error_description", out var errorDescVal);
            code = codeVal ?? string.Empty;
            state = stateVal ?? string.Empty;
            error = errorVal ?? string.Empty;
            errorDescription = errorDescVal ?? string.Empty;
            return !string.IsNullOrEmpty(code) || !string.IsNullOrEmpty(error);
        }

        if (input.Contains('='))
        {
            var query = ParseQuery(input);
            query.TryGetValue("code", out var codeVal);
            query.TryGetValue("state", out var stateVal);
            query.TryGetValue("error", out var errorVal);
            query.TryGetValue("error_description", out var errorDescVal);
            code = codeVal ?? string.Empty;
            state = stateVal ?? string.Empty;
            error = errorVal ?? string.Empty;
            errorDescription = errorDescVal ?? string.Empty;
            return !string.IsNullOrEmpty(code) || !string.IsNullOrEmpty(error);
        }

        // Lichess authorization codes match ^[A-Za-z0-9_]+$.
        code = input;
        return true;
    }

