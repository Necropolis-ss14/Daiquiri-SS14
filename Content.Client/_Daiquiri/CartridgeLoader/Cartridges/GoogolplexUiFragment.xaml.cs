    /// <summary>
    /// Label has no auto-wrap in Robust, so long server messages are broken into lines that
    /// fit the PDA instead of being clipped at the screen edge.
    /// </summary>
    private static string WrapChessText(string text, int maxChars = 40)
    {
        if (string.IsNullOrEmpty(text) || text.Length <= maxChars)
            return text;

        var words = text.Split(' ', StringSplitOptions.RemoveEmptyEntries);
        var builder = new System.Text.StringBuilder(text.Length + 8);
        var lineLength = 0;

        foreach (var word in words)
        {
            if (lineLength > 0 && lineLength + 1 + word.Length > maxChars)
            {
                builder.Append('\n');
                lineLength = 0;
            }
            else if (lineLength > 0)
            {
                builder.Append(' ');
                lineLength++;
            }

            builder.Append(word);
            lineLength += word.Length;
        }

        return builder.ToString();
    }

