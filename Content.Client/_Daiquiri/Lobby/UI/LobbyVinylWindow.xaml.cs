using System.Linq;
using System.Numerics;
using Content.Client._Starlight.Achievement;
using Content.Client.Players.PlayTimeTracking;
using Content.Shared._Daiquiri.CCVar;
using Content.Shared._Daiquiri.Lobby;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Prototypes;

namespace Content.Client._Daiquiri.Lobby.UI;

/// <summary>
/// Daiquiri
/// Окно выбора своей пластинки в лобби.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class LobbyVinylWindow : DefaultWindow
{
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IClientAchievementManager _achievements = default!;
    [Dependency] private JobRequirementsManager _playtime = default!;
    [Dependency] private IClientVinylGrants _vinylGrants = default!;

    public LobbyVinylWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        VinylGrid.Columns = 4;
        Resizable = false;
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        _achievements.AchievementsUpdated += Rebuild;
        _playtime.Updated += Rebuild;
        _vinylGrants.Updated += Rebuild;
        Rebuild();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        _achievements.AchievementsUpdated -= Rebuild;
        _playtime.Updated -= Rebuild;
        _vinylGrants.Updated -= Rebuild;
    }

    private void Rebuild()
    {
        if (Disposed || VinylGrid.Disposed)
            return;

        VinylGrid.RemoveAllChildren();

        var selected = _cfg.GetCVar(DaiquiriCCVars.LobbyVinyl);
        var playtime = _playtime.FetchOverallPlaytime();

        var vinyls = _prototypes.EnumeratePrototypes<LobbyVinylPrototype>()
            .OrderBy(UnlockRank)
            .ThenBy(vinyl => vinyl.RequiredPlaytime)
            .ThenBy(vinyl => vinyl.ID, StringComparer.Ordinal);

        foreach (var vinyl in vinyls)
        {
            var unlocked = LobbyVinyls.IsUnlocked(vinyl, _achievements, playtime, _vinylGrants);
            VinylGrid.AddChild(BuildCard(vinyl, unlocked, selected == vinyl.ID));
        }
    }

    private static int UnlockRank(LobbyVinylPrototype vinyl)
    {
        if (vinyl.GrantOnly)
            return 3;

        if (vinyl.RequiredAchievement != null)
            return 2;

        return vinyl.RequiredPlaytime > TimeSpan.Zero ? 1 : 0;
    }

    private Control BuildCard(LobbyVinylPrototype vinyl, bool unlocked, bool selected)
    {
        var button = new Button
        {
            ToggleMode = true,
            Pressed = selected,
            Disabled = !unlocked,
            MinSize = new Vector2(160f, 0f),
            HorizontalExpand = true,
            ToolTip = unlocked ? null : LobbyVinyls.UnlockDescription(vinyl, _prototypes),
        };

        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 4,
            Margin = new Thickness(6f, 6f, 6f, 6f),
        };

        content.AddChild(new TextureRect
        {
            TexturePath = LobbyVinyls.Frame(vinyl, 2),
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            MinSize = new Vector2(96f, 96f),
            HorizontalAlignment = HAlignment.Center,
        });

        content.AddChild(new Label
        {
            Text = Loc.GetString(vinyl.Name),
            HorizontalAlignment = HAlignment.Center,
            FontColorOverride = unlocked ? Color.White : Color.Gray,
        });

        if (unlocked)
        {
            content.AddChild(new Label
            {
                Text = Loc.GetString(selected ? "lobby-vinyl-status-selected" : "lobby-vinyl-status-unlocked"),
                HorizontalAlignment = HAlignment.Center,
                FontColorOverride = selected ? Color.Gold : Color.PaleGreen,
            });
        }
        else
        {
            content.AddChild(new Label
            {
                Text = LobbyVinyls.UnlockDescription(vinyl, _prototypes)
                       ?? Loc.GetString("lobby-vinyl-status-locked"),
                HorizontalAlignment = HAlignment.Center,
                FontColorOverride = Color.LightGray,
                ClipText = true,
            });
        }

        button.AddChild(content);
        button.OnPressed += _ => OnVinylPressed(vinyl, unlocked);
        return button;
    }

    private void OnVinylPressed(LobbyVinylPrototype vinyl, bool unlocked)
    {
        if (!unlocked)
            return;

        _cfg.SetCVar(DaiquiriCCVars.LobbyVinyl, vinyl.ID);
        Rebuild();
    }
}
