using System;
using Content.Client.Gameplay;
using Content.Client.UserInterface.Systems.Info;
using Content.Shared._Starlight.CCVar;
using Content.Shared._Starlight.UserInterface;
using Robust.Client.AutoGenerated;
using Robust.Client.State;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._Daiquiri.Options.UI;

/// <summary>
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GlassThemePrompt : Control
{
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IStateManager _stateManager = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    private const float CardWidth = 1080f;
    private const float CardHeight = 560f;
    private const float ScreenMargin = 32f;
    private const float SlideDuration = 0.45f;

    private const float SlideInDistance = 340f;

    private const float RulesWaitUnknown = -1f;

    private InfoUIController? _info;
    private float _slide;
    private float _rulesWait;
    private float _entrance = -1f;
    private string? _rulesIntroText;
    private bool _rulesShown;
    private bool _rulesAccepted;

    private enum EnterSide : byte
    {
        Bottom,
        Right,
        Left,
    }

    private EnterSide _enterSide = EnterSide.Bottom;

    public static GlassThemePrompt Open(IUserInterfaceManager ui)
    {
        var prompt = new GlassThemePrompt();
        ui.WindowRoot.AddChild(prompt);
        LayoutContainer.SetAnchorPreset(prompt, LayoutContainer.LayoutPreset.Wide);
        return prompt;
    }

    public GlassThemePrompt()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _stateManager.OnStateChanged += OnStateChanged;

        SetBodyText(WelcomeLine1, Loc.GetString("ui-newcomer-welcome-1"));
        SetBodyText(WelcomeLine2, Loc.GetString("ui-newcomer-welcome-2"));
        SetBodyText(ThemeLine1, Loc.GetString("ui-glass-prompt-theme-line"));
        SetBodyText(ThemeLine2, Loc.GetString("ui-glass-prompt-theme-line2"));
        ShowWelcomePage();

        WelcomeNext.OnPressed += _ => ShowRulesPage();
        ShowRulesButton.OnPressed += _ => RevealRules();
        RulesAccept.OnPressed += _ => AcceptRules();
        RulesBack.OnPressed += _ => ShowWelcomePage();
        ThemeBack.OnPressed += _ => ShowRulesPage();
        DoneButton.OnPressed += _ => Finish();

        ThemePicker.Select(_cfg.GetCVar(StarlightCCVars.StyleTheme));
        ThemePicker.OnPicked += () =>
        {
            if (ThemePicker.Selected != null)
                _cfg.SetCVar(StarlightCCVars.StyleTheme, ThemePicker.Selected);
        };

        AccentPicker.SetUseCustom(_cfg.GetCVar(StarlightCCVars.StyleCustomAccent));
        if (Color.TryFromHex(_cfg.GetCVar(StarlightCCVars.StyleAccent), out var accent))
            AccentPicker.Select(accent);

        AccentPicker.OnPicked += () =>
        {
            _cfg.SetCVar(StarlightCCVars.StyleCustomAccent, AccentPicker.UseCustom);
            _cfg.SetCVar(StarlightCCVars.StyleAccent, AccentPicker.Selected.ToHex());
        };

        SecondaryAccentPicker.SetTitle("ui-options-style-secondary-accent");
        SecondaryAccentPicker.SetUseCustom(_cfg.GetCVar(StarlightCCVars.StyleCustomSecondaryAccent));
        if (Color.TryFromHex(_cfg.GetCVar(StarlightCCVars.StyleSecondaryAccent), out var secondaryAccent))
            SecondaryAccentPicker.Select(secondaryAccent);

        SecondaryAccentPicker.OnPicked += () =>
        {
            _cfg.SetCVar(StarlightCCVars.StyleCustomSecondaryAccent, SecondaryAccentPicker.UseCustom);
            _cfg.SetCVar(StarlightCCVars.StyleSecondaryAccent, SecondaryAccentPicker.Selected.ToHex());
        };

        _info = UserInterfaceManager.GetUIController<InfoUIController>();
        _info.ClaimRulesForNewcomer();
    }

    private void ShowWelcomePage()
    {
        WelcomePage.Visible = true;
        RulesPage.Visible = false;
        ThemePage.Visible = false;
        TitleLabel.Text = Loc.GetString("ui-glass-prompt-title");
        StartEntrance(EnterSide.Bottom);
    }

    private void ShowRulesPage()
    {
        WelcomePage.Visible = false;
        RulesPage.Visible = true;
        ThemePage.Visible = false;
        TitleLabel.Text = Loc.GetString("ui-newcomer-rules-title");
        StartEntrance(EnterSide.Right);

        RefreshRulesIntro();
    }

    private void RefreshRulesIntro()
    {
        var text = Loc.GetString(RulesOptional
            ? "ui-newcomer-rules-line-optional"
            : "ui-newcomer-rules-line");

        if (_rulesIntroText == text)
            return;

        _rulesIntroText = text;
        SetBodyText(RulesIntro, text);
    }

    private void StartEntrance(EnterSide side)
    {
        _enterSide = side;
        _slide = 0f;
    }

    private static void SetBodyText(RichTextLabel label, string text)
    {
        var color = label.TryGetStyleProperty<Color>(Label.StylePropertyFontColor, out var styleColor)
            ? styleColor
            : Color.White;

        label.SetMessage(text, color);
    }

    private bool RulesOptional => _info is { RulesInfoReceived: true, RulesRequired: false };

    private void RevealRules()
    {
        if (_rulesShown)
            return;

        _rulesShown = true;
        RulesIntro.Visible = false;
        ShowRulesButton.Visible = false;
        RulesView.Visible = true;
        RulesAccept.Disabled = true;

        if (RulesOptional)
        {
            UnlockRulesAccept();
            return;
        }

        _rulesWait = _info is { RulesInfoReceived: true } ? _info.RulesWaitTime : RulesWaitUnknown;
        UpdateRulesWaitLabel();
    }

    private void AcceptRules()
    {
        if (!_rulesAccepted && _info is { RulesRequired: true })
        {
            _info.AcceptRules();
            _rulesAccepted = true;
        }

        ShowThemePage();
    }

    private void UnlockRulesAccept()
    {
        _rulesWait = 0f;
        RulesAccept.Text = Loc.GetString(RulesOptional ? "ui-newcomer-rules-read" : "ui-newcomer-rules-accept");
        RulesAccept.Disabled = false;
        RulesWaitLabel.Text = string.Empty;
    }

    private void ShowThemePage()
    {
        WelcomePage.Visible = false;
        RulesPage.Visible = false;
        TitleLabel.Text = Loc.GetString("ui-glass-prompt-theme");
        ThemePage.Visible = true;
        StartEntrance(EnterSide.Left);
    }

    private void Finish()
    {
        _cfg.SetCVar(StarlightCCVars.UIGlassThemeSeen, true);

        if (IsLiquidGlassTheme())
            UserInterfaceManager.CreateWindow<LiquidGlassSettingsWindow>().OpenCentered();

        Close();
    }

    private bool IsLiquidGlassTheme()
    {
        return _prototype.TryIndex<StyleThemePrototype>(_cfg.GetCVar(StarlightCCVars.StyleTheme), out var proto)
               && proto.LiquidGlass;
    }

    private void OnStateChanged(StateChangedEventArgs args)
    {
        if (args.OldState is GameplayState)
            Close();
    }

    private void Close()
    {
        _stateManager.OnStateChanged -= OnStateChanged;
        Orphan();
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (disposing)
            _stateManager.OnStateChanged -= OnStateChanged;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_slide < 1f)
            _slide = MathF.Min(1f, _slide + args.DeltaSeconds / SlideDuration);

        ArrangeCard();

        if (RulesPage.Visible && !_rulesShown)
            RefreshRulesIntro();

        if (!_rulesShown || !RulesAccept.Disabled)
            return;

        if (_rulesWait == RulesWaitUnknown)
        {
            if (_info is not { RulesInfoReceived: true })
                return;

            if (RulesOptional)
            {
                UnlockRulesAccept();
                return;
            }

            _rulesWait = _info.RulesWaitTime;
            UpdateRulesWaitLabel();
        }

        if (_rulesWait > 0f)
        {
            _rulesWait = MathF.Max(0f, _rulesWait - args.DeltaSeconds);
            UpdateRulesWaitLabel();
            return;
        }

        UnlockRulesAccept();
    }

    private void UpdateRulesWaitLabel()
    {
        RulesWaitLabel.Text = _rulesWait == RulesWaitUnknown
            ? string.Empty
            : Loc.GetString("ui-newcomer-rules-wait", ("time", MathF.Ceiling(_rulesWait)));
    }

    private void ArrangeCard()
    {
        var width = MathF.Min(CardWidth, MathF.Max(480f, Size.X - ScreenMargin * 2f));
        var height = MathF.Min(CardHeight, MathF.Max(240f, Size.Y - ScreenMargin * 2f));
        if (Card.SetWidth != width)
            Card.SetWidth = width;
        if (Card.SetHeight != height)
            Card.SetHeight = height;

        var progress = 1f - MathF.Pow(1f - Math.Clamp(_slide, 0f, 1f), 3f);
        if (Math.Abs(progress - _entrance) < 0.001f)
            return;

        _entrance = progress;

        var distance = (1f - progress) * SlideInDistance * 2f;
        var margin = _enterSide switch
        {
            EnterSide.Right => new Thickness(distance, 0f, 0f, 0f),
            EnterSide.Left => new Thickness(0f, 0f, distance, 0f),
            _ => new Thickness(0f, distance, 0f, 0f),
        };

        Card.Margin = margin;
        Card.Modulate = new Color(1f, 1f, 1f, progress);
    }
}
