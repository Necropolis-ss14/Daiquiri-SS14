            ? string.Empty
            : $"Режим: {_chessTimeControl}";

        ChessPlayStatusLabel.Text = WrapChessText(string.IsNullOrEmpty(_chessGameStatusText)
            ? (inProgress ? "Партия идёт." : "Партия завершена.")
            : _chessGameStatusText);

        if (_chessDelegated && !string.IsNullOrEmpty(_chessOwnerName))
        {
