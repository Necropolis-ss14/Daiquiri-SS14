using System;
using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Timing;

namespace Content.Client._Daiquiri.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class GoogolplexUiFragment : BoxContainer
{
    private readonly IResourceCache _resourceCache = IoCManager.Resolve<IResourceCache>();

    public GoogolplexUiFragment()
    {
        RobustXamlLoader.Load(this);

        Background.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#C7C7C7"),
        };

        Wordmark.Texture = _resourceCache.GetTexture("/Textures/_Daiquiri/Googolplex/googolplex_wordmark.png");

        SearchPanel.PanelOverride = new StyleBoxTexture
        {
            Texture = _resourceCache.GetTexture("/Textures/_Daiquiri/Googolplex/search_bar.png"),
            Mode = StyleBoxTexture.StretchMode.Stretch,
        };

        var pixelFont = new VectorFont(_resourceCache.GetResource<FontResource>("/Fonts/_Daiquiri/PressStart2P-Regular.ttf"), 12);
        var smallPixelFont = new VectorFont(_resourceCache.GetResource<FontResource>("/Fonts/_Daiquiri/PressStart2P-Regular.ttf"), 8);
        SearchBox.StyleBoxOverride = new StyleBoxEmpty();
        SearchBox.ModulateSelfOverride = Color.Black;
        
        // Create a custom stylesheet for the LineEdit with pixel font
        var lineEditSheet = new Stylesheet([
            StylesheetHelpers.Element<LineEdit>()
                .Prop("font", pixelFont)
                .Prop("font-color", Color.Black)
                .Prop("cursor-color", Color.Black)
                .Prop("selection-color", Color.FromHex("#DC7500"))
        ]);
        SearchBox.Stylesheet = lineEditSheet;

        SearchButton.TextureNormal = _resourceCache.GetTexture("/Textures/_Daiquiri/Googolplex/search_icon.png");
        SearchButton.OnPressed += OnSearchPressed;

        SitesButton.TextureNormal = _resourceCache.GetTexture("/Textures/_Daiquiri/Googolplex/btn-site.png");
        SitesButton.OnPressed += OnSitesPressed;
        NewsButton.TextureNormal = _resourceCache.GetTexture("/Textures/_Daiquiri/Googolplex/btn-news.png");
        GoodsButton.TextureNormal = _resourceCache.GetTexture("/Textures/_Daiquiri/Googolplex/btn-goods.png");

        // Forum page setup (StarWay forum)
        ForumBanner.Texture = _resourceCache.GetTexture("/Textures/_Daiquiri/Googolplex/starway.png");
        ForumBackButton.OnPressed += OnBackPressed;
        var forumBackButtonLabel = (Label)ForumBackButton.GetChild(0);
        forumBackButtonLabel.FontOverride = pixelFont;

        // Results page setup
        ResultsDomainLabel.Text = "starway.nt";
        ResultsDomainLabel.FontOverride = pixelFont;
        ResultsDomainLabel.FontColorOverride = Color.Black;

        ResultsTitle.Text = "StarWay";
        ResultsTitle.FontOverride = pixelFont;
        ResultsTitle.FontColorOverride = Color.FromHex("#0066CC");
        ResultsTitleButton.OnPressed += OnResultClicked;

        ResultsDescription.Text = "Изучай вселенную StarWay, смотрите видео, читайте новости, делитесь впечатлениями с друзьями и пользователями со всего мира.";
        ResultsDescription.FontOverride = smallPixelFont;
        ResultsDescription.FontColorOverride = Color.Black;

        ResultsIcon.Texture = _resourceCache.GetTexture("/Textures/_Daiquiri/Googolplex/starway.png");

        ProgressBackground.Texture = _resourceCache.GetTexture("/Textures/_Daiquiri/Googolplex/search_bar.png");
        SearchProgress.MinValue = 0;
        SearchProgress.MaxValue = 100;
        SearchProgress.Value = 0;
        SearchProgress.HorizontalExpand = true;
        SearchProgress.HorizontalAlignment = HAlignment.Center;
        SearchProgress.Margin = new Thickness(36, 0, 36, 0);

        BackButton.OnPressed += OnBackPressed;
        var backButtonLabel = (Label)BackButton.GetChild(0);
        backButtonLabel.FontOverride = pixelFont;

        // StarWay page setup
        StarWayDomainLabel.Text = "starway.nt";
        StarWayDomainLabel.FontOverride = pixelFont;
        StarWayDomainLabel.FontColorOverride = Color.Black;

        StarWayTitle.Text = "StarWay";
        StarWayTitle.FontOverride = pixelFont;
        StarWayTitle.FontColorOverride = Color.FromHex("#0066CC");

        StarWayIcon.Texture = _resourceCache.GetTexture("/Textures/_Daiquiri/Googolplex/starway.png");

        StarWayBanner.Texture = _resourceCache.GetTexture("/Textures/_Daiquiri/Googolplex/starway.png");

        StarWayBackButton.OnPressed += OnBackPressed;
        var starWayBackButtonLabel = (Label)StarWayBackButton.GetChild(0);
        starWayBackButtonLabel.FontOverride = pixelFont;
    }

    private void OnSearchPressed(BaseButton.ButtonEventArgs e)
    {
        var query = SearchBox.Text?.Trim() ?? "";
        if (string.IsNullOrEmpty(query))
            return;

        if (IsStarWayQuery(query))
        {
            ShowStarWayPage();
        }
        else
        {
            ShowResultsPage(query);
        }
    }

    private bool IsStarWayQuery(string query)
    {
        var normalized = query.ToLowerInvariant()
            .Replace("ё", "е")
            .Replace(" ", "");
        return normalized.Contains("starway") ||
               normalized.Contains("старвей");
    }

    private void ShowResultsPage(string query)
    {
        Wordmark.Visible = false;
        SearchPanel.Visible = false;
        Tabs.Visible = false;
        ResultsPage.Visible = true;

        ResultsDomainLabel.Text = $"starway.nt > {query}";
        ResultsTitle.Text = "StarWay";
        ResultsDescription.Text = $"Результаты поиска по запросу \u00AB{query}\u00BB. Изучайте вселенную StarWay, смотрите видео, читайте новости, делитесь впечатлениями с пользователями со всего мира.";

        SearchProgress.Value = 0;
        var startTime = DateTime.UtcNow;
        Timer.Spawn(16, UpdateProgressBar);
        
        void UpdateProgressBar()
        {
            var elapsed = (DateTime.UtcNow - startTime).TotalMilliseconds;
            var progress = (float)Math.Min(elapsed / 3000.0 * 100, 100);
            SearchProgress.Value = progress;
            if (progress < 100)
                Timer.Spawn(16, UpdateProgressBar);
        }
    }

    private void ShowStarWayPage()
    {
        Wordmark.Visible = false;
        SearchPanel.Visible = false;
        Tabs.Visible = false;
        StarWayPage.Visible = true;

        StarWayDomainLabel.Text = "starway.nt";
        StarWayTitle.Text = "StarWay";
    }

    private void OnResultClicked(BaseButton.ButtonEventArgs e)
    {
        ShowStarWayPage();
    }

    private void OnBackPressed(BaseButton.ButtonEventArgs e)
    {
        ResultsPage.Visible = false;
        StarWayPage.Visible = false;
        ForumPage.Visible = false;
        Wordmark.Visible = true;
        SearchPanel.Visible = true;
        Tabs.Visible = true;
        SearchBox.Text = "";
    }

    private void OnSitesPressed(BaseButton.ButtonEventArgs e)
    {
        Wordmark.Visible = false;
        SearchPanel.Visible = false;
        Tabs.Visible = false;
        ForumPage.Visible = true;
    }
}