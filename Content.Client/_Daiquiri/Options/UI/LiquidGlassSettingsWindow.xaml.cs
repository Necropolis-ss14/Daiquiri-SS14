using Content.Client._Starlight.Options.UI;
using Content.Shared._Starlight.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.IoC;
using Robust.Shared.Localization;
using Robust.Shared.Maths;

namespace Content.Client._Daiquiri.Options.UI;

[GenerateTypedNameReferences]
public sealed partial class LiquidGlassSettingsWindow : DefaultWindow
{
    [Dependency] private IConfigurationManager _cfg = default!;

    public LiquidGlassSettingsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        EnabledCheckBox.Pressed = _cfg.GetCVar(StarlightCCVars.UILiquidGlassEnabled);
        EnabledCheckBox.OnToggled += args =>
            _cfg.SetCVar(StarlightCCVars.UILiquidGlassEnabled, args.Pressed);

        SetupPercentSlider(BlurSlider, StarlightCCVars.UILiquidGlassBlur);
        SetupPercentSlider(RefractionSlider, StarlightCCVars.UILiquidGlassRefraction);
        SetupPercentSlider(HighlightSlider, StarlightCCVars.UILiquidGlassHighlight);
        SetupPercentSlider(OpacitySlider, StarlightCCVars.UILiquidGlassOpacity);
        SetupPercentSlider(TintSlider, StarlightCCVars.UILiquidGlassTint);
        SetupPercentSlider(CornerSlider, StarlightCCVars.UILiquidGlassCornerRadius);

        TintEnabledCheckBox.Pressed = _cfg.GetCVar(StarlightCCVars.UILiquidGlassTintEnabled);
        TintEnabledCheckBox.OnToggled += args =>
        {
            _cfg.SetCVar(StarlightCCVars.UILiquidGlassTintEnabled, args.Pressed);
            TintColorSlider.Visible = args.Pressed;
        };
        TintColorSlider.Visible = TintEnabledCheckBox.Pressed;

        if (Color.TryFromHex(_cfg.GetCVar(StarlightCCVars.UILiquidGlassTintColor), out var tint))
            TintColorSlider.Slider.Color = tint;
        TintColorSlider.Slider.OnColorChanged += color =>
            _cfg.SetCVar(StarlightCCVars.UILiquidGlassTintColor, color.ToHex());

        SetupQualitySlider();

        AnimateCheckBox.Pressed = _cfg.GetCVar(StarlightCCVars.UILiquidGlassAnimate);
        AnimateCheckBox.OnToggled += args =>
            _cfg.SetCVar(StarlightCCVars.UILiquidGlassAnimate, args.Pressed);

        ResetButton.OnPressed += _ => ResetToDefaults();
        DoneButton.OnPressed += _ => Close();
    }

    private void SetupPercentSlider(OptionSlider slider, CVarDef<int> cvar)
    {
        slider.Slider.MinValue = 0;
        slider.Slider.MaxValue = 100;
        slider.Slider.SetValueWithoutEvent(_cfg.GetCVar(cvar));
        slider.ValueLabel.Text = $"{_cfg.GetCVar(cvar)}%";
        slider.Slider.OnValueChanged += args =>
        {
            var value = (int) args.Value;
            _cfg.SetCVar(cvar, value);
            slider.ValueLabel.Text = $"{value}%";
        };
    }

    private void SetupQualitySlider()
    {
        QualitySlider.Slider.MinValue = 0;
        QualitySlider.Slider.MaxValue = 2;
        QualitySlider.Slider.SetValueWithoutEvent(_cfg.GetCVar(StarlightCCVars.UILiquidGlassQuality));
        QualitySlider.ValueLabel.Text = QualityLabel(_cfg.GetCVar(StarlightCCVars.UILiquidGlassQuality));
        QualitySlider.Slider.OnValueChanged += args =>
        {
            var value = (int) args.Value;
            _cfg.SetCVar(StarlightCCVars.UILiquidGlassQuality, value);
            QualitySlider.ValueLabel.Text = QualityLabel(value);
        };
    }

    private void ResetToDefaults()
    {
        _cfg.SetCVar(StarlightCCVars.UILiquidGlassEnabled, StarlightCCVars.UILiquidGlassEnabled.DefaultValue);
        _cfg.SetCVar(StarlightCCVars.UILiquidGlassBlur, StarlightCCVars.UILiquidGlassBlur.DefaultValue);
        _cfg.SetCVar(StarlightCCVars.UILiquidGlassRefraction, StarlightCCVars.UILiquidGlassRefraction.DefaultValue);
        _cfg.SetCVar(StarlightCCVars.UILiquidGlassHighlight, StarlightCCVars.UILiquidGlassHighlight.DefaultValue);
        _cfg.SetCVar(StarlightCCVars.UILiquidGlassOpacity, StarlightCCVars.UILiquidGlassOpacity.DefaultValue);
        _cfg.SetCVar(StarlightCCVars.UILiquidGlassTint, StarlightCCVars.UILiquidGlassTint.DefaultValue);
        _cfg.SetCVar(StarlightCCVars.UILiquidGlassTintEnabled, StarlightCCVars.UILiquidGlassTintEnabled.DefaultValue);
        _cfg.SetCVar(StarlightCCVars.UILiquidGlassTintColor, StarlightCCVars.UILiquidGlassTintColor.DefaultValue);
        _cfg.SetCVar(StarlightCCVars.UILiquidGlassCornerRadius, StarlightCCVars.UILiquidGlassCornerRadius.DefaultValue);
        _cfg.SetCVar(StarlightCCVars.UILiquidGlassQuality, StarlightCCVars.UILiquidGlassQuality.DefaultValue);
        _cfg.SetCVar(StarlightCCVars.UILiquidGlassAnimate, StarlightCCVars.UILiquidGlassAnimate.DefaultValue);

        RefreshValues();
    }

    private void RefreshValues()
    {
        EnabledCheckBox.Pressed = _cfg.GetCVar(StarlightCCVars.UILiquidGlassEnabled);
        RefreshPercentSlider(BlurSlider, StarlightCCVars.UILiquidGlassBlur);
        RefreshPercentSlider(RefractionSlider, StarlightCCVars.UILiquidGlassRefraction);
        RefreshPercentSlider(HighlightSlider, StarlightCCVars.UILiquidGlassHighlight);
        RefreshPercentSlider(OpacitySlider, StarlightCCVars.UILiquidGlassOpacity);
        RefreshPercentSlider(TintSlider, StarlightCCVars.UILiquidGlassTint);
        RefreshPercentSlider(CornerSlider, StarlightCCVars.UILiquidGlassCornerRadius);

        TintEnabledCheckBox.Pressed = _cfg.GetCVar(StarlightCCVars.UILiquidGlassTintEnabled);
        TintColorSlider.Visible = TintEnabledCheckBox.Pressed;
        if (Color.TryFromHex(_cfg.GetCVar(StarlightCCVars.UILiquidGlassTintColor), out var tint))
            TintColorSlider.Slider.Color = tint;

        var quality = _cfg.GetCVar(StarlightCCVars.UILiquidGlassQuality);
        QualitySlider.Slider.SetValueWithoutEvent(quality);
        QualitySlider.ValueLabel.Text = QualityLabel(quality);

        AnimateCheckBox.Pressed = _cfg.GetCVar(StarlightCCVars.UILiquidGlassAnimate);
    }

    private void RefreshPercentSlider(OptionSlider slider, CVarDef<int> cvar)
    {
        var value = _cfg.GetCVar(cvar);
        slider.Slider.SetValueWithoutEvent(value);
        slider.ValueLabel.Text = $"{value}%";
    }

    private static string QualityLabel(int value) => value switch
    {
        0 => Loc.GetString("ui-liquid-glass-quality-low"),
        2 => Loc.GetString("ui-liquid-glass-quality-high"),
        _ => Loc.GetString("ui-liquid-glass-quality-medium"),
    };
}
