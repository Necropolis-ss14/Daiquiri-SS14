    private static int ChessTimeControlMinutes(string timeControl)
    {
        var plus = timeControl.IndexOf('+');
        var minutes = plus >= 0 ? timeControl[..plus] : timeControl;
        return int.TryParse(minutes, out var value) ? Math.Max(0, value) : 0;
    }

    private void StartChessSeek()
    {
        if (ChessGameInProgress)
            return;

        if (!_chessLinkLinked || _chessLinkTokenExpired)
        {
            ShowChessStatus("Сначала привяжите аккаунт Lichess.", true);
            return;
