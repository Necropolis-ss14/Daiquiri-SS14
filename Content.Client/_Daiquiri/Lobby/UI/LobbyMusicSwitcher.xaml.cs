using Timer = Robust.Shared.Timing.Timer;

namespace Content.Client._Daiquiri.Lobby.UI;

/// <summary>
/// Manual lobby music switcher (previous / current track / next) with a rocking vinyl.
/// Replaces the servers hub in the lobby. Wired up by <see cref="LobbyState"/>.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class LobbyMusicSwitcher : BoxContainer
{
    private static readonly string[] RockFrames =
    {
        "/Textures/_Daiquiri/Interface/Vinyl/classic_0.png",
        "/Textures/_Daiquiri/Interface/Vinyl/classic_1.png",
        "/Textures/_Daiquiri/Interface/Vinyl/classic_2.png",
        "/Textures/_Daiquiri/Interface/Vinyl/classic_3.png",
        "/Textures/_Daiquiri/Interface/Vinyl/classic_4.png",
        "/Textures/_Daiquiri/Interface/Vinyl/classic_5.png",
    };

    private const int RockMs = 180;

    private int _rockIndex;
    private bool _rocking;
    private ContentAudioSystem? _audio;
    private IConfigurationManager? _cfg;
    private IPrototypeManager? _prototypes;
    private string[] _frames = RockFrames;

    /// <summary>
    /// Daiquiri
    /// </summary>
    private bool AnimPaused()
    {
        try
        {
            _audio ??= IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<ContentAudioSystem>();
        }
        catch
        {
            return false;
        }
        return _audio?.LobbyMusicPaused ?? false;
    }

    public LobbyMusicSwitcher()
    {
        RobustXamlLoader.Load(this);
        VinylRect.OnKeyBindDown += OnVinylInput;
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _rocking = true;

        try
        {
            _cfg ??= IoCManager.Resolve<IConfigurationManager>();
            _prototypes ??= IoCManager.Resolve<IPrototypeManager>();
            _cfg.OnValueChanged(DaiquiriCCVars.LobbyVinyl, OnVinylChanged, true);
        }
        catch
        {
        }

        RockTick();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _rocking = false;

        if (_cfg != null)
            _cfg.UnsubValueChanged(DaiquiriCCVars.LobbyVinyl, OnVinylChanged);
    }

    /// <summary>
    /// Daiquiri
    /// </summary>
    private void OnVinylChanged(string vinyl)
    {
        UpdateFrames();
    }

    /// <summary>
    /// Daiquiri
    /// </summary>
    private void UpdateFrames()
    {
        if (_cfg == null || _prototypes == null)
            return;

        var id = _cfg.GetCVar(DaiquiriCCVars.LobbyVinyl);
        if (!_prototypes.TryIndex<LobbyVinylPrototype>(id, out var vinyl)
            && !_prototypes.TryIndex<LobbyVinylPrototype>(LobbyVinyls.DefaultId, out vinyl))
            return;

        _frames = LobbyVinyls.Frames(vinyl);
        _rockIndex = 0;
        VinylRect.TexturePath = _frames[0];
    }

    private void RockTick()
    {
        if (!_rocking)
            return;

        // Rocking continues even mid-bounce, but freezes while paused.
        if (!AnimPaused())
        {
            _rockIndex = (_rockIndex + 1) % _frames.Length;
            VinylRect.TexturePath = _frames[_rockIndex];
        }
        Timer.Spawn(RockMs, RockTick);
    }

    private bool _bouncing;

    // Daiquiri
    // Clicks are ignored until the whole sequence finishes.
    private static readonly float[] BounceHeights =
    {
        -10f, -24f, -40f, -56f, -70f, -54f, -36f, -18f, 0f, -26f, -10f, 0f,
    };
    private const int BounceMs = 60;

    private void OnVinylInput(GUIBoundKeyEventArgs args)
    {
        if (args.Function != EngineKeyFunctions.UIClick || _bouncing || AnimPaused())
            return;

        _bouncing = true;
        BounceTick(0);
    }

    private void BounceTick(int step)
    {
        if (!_bouncing)
            return;

        if (step >= BounceHeights.Length)
        {
            VinylRect.Margin = new Thickness(0f);
            _bouncing = false;
            return;
        }
        var h = BounceHeights[step];
        VinylRect.Margin = new Thickness(0f, h, 0f, -h);
        Timer.Spawn(BounceMs, () => BounceTick(step + 1));
    }
}
