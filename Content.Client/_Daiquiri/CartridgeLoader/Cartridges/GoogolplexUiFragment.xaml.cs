    private void BuildChessBoard()
    {
        var rsi = _resourceCache.GetResource<RSIResource>(
            new ResPath("/Textures/Objects/Fun/Tabletop/chess_pieces.rsi")).RSI;

        _chessPieceTextures.Clear();
        foreach (var stateName in new[]
                 {
                     "w_pawn", "w_rook", "w_knight", "w_bishop", "w_king", "w_queen",
                     "b_pawn", "b_rook", "b_knight", "b_bishop", "b_king", "b_queen",
                 })
        {
            if (rsi.TryGetState(stateName, out var state))
                _chessPieceTextures[stateName] = state.Frame0;
        }

        ChessBoardGrid.RemoveAllChildren();

        for (var row = 0; row < 8; row++)
        {
            for (var col = 0; col < 8; col++)
            {
                var square = new PanelContainer
                {
                    MinSize = new Vector2(ChessCellSize, ChessCellSize),
                    PanelOverride = CreateChessSquareStyle(row, col),
                    // The grid (or the transparent overlay above it) handles board input.
                    // Decorative squares must never intercept it.
                    MouseFilter = MouseFilterMode.Ignore,
                };

                var cell = new LayoutContainer();
                square.AddChild(cell);

                // A TextureRect with CanShrink reports a zero minimum size, so the cell
                // keeps the exact 28 px size instead of growing to the piece texture size.
                var button = new TextureRect
                {
                    Texture = null,
                    CanShrink = true,
                    Stretch = TextureRect.StretchMode.KeepAspectCentered,
                    MouseFilter = MouseFilterMode.Ignore,
                };
                LayoutContainer.SetAnchorLeft(button, 0f);
                LayoutContainer.SetAnchorTop(button, 0f);
                LayoutContainer.SetAnchorRight(button, 1f);
                LayoutContainer.SetAnchorBottom(button, 1f);
                cell.AddChild(button);

                var dot = new TextureRect
                {
                    Texture = GetChessDotTexture(),
                    MinSize = new Vector2(ChessDotSize, ChessDotSize),
                    // Without CanShrink the 16 px texture raises DesiredSize above the
                    // 12 px anchor box and LayoutContainer grows the dot to the right and
                    // down, which makes the green circle look off-centre.
                    CanShrink = true,
                    Stretch = TextureRect.StretchMode.KeepAspectCentered,
                    MouseFilter = MouseFilterMode.Ignore,
                    Visible = false,
                };
                LayoutContainer.SetAnchorLeft(dot, 0.5f);
                LayoutContainer.SetAnchorTop(dot, 0.5f);
                LayoutContainer.SetAnchorRight(dot, 0.5f);
                LayoutContainer.SetAnchorBottom(dot, 0.5f);
                LayoutContainer.SetMarginLeft(dot, -ChessDotSize / 2f);
                LayoutContainer.SetMarginTop(dot, -ChessDotSize / 2f);
                LayoutContainer.SetMarginRight(dot, ChessDotSize / 2f);
                LayoutContainer.SetMarginBottom(dot, ChessDotSize / 2f);
                cell.AddChild(dot);

                ChessBoardGrid.AddChild(square);
                _chessCells[row, col] = button;
                _chessDots[row, col] = dot;
            }
        }

        RenderChessBoard();
    }

    /// <summary>
    /// A soft green dot drawn on the squares a selected piece may move to. Generated once
    /// because the UI has no circular style box.
    /// </summary>
    private static Texture GetChessDotTexture()
    {
        if (_chessDotTexture != null)
            return _chessDotTexture;

        const int size = 16;
        var image = new SixLabors.ImageSharp.Image<Rgba32>(size, size);
        var center = (size - 1) / 2f;
        var radius = size / 2f - 0.5f;

        for (var y = 0; y < size; y++)
        {
            for (var x = 0; x < size; x++)
            {
                var dx = x - center;
                var dy = y - center;
                var distance = MathF.Sqrt(dx * dx + dy * dy);
                var alpha = Math.Clamp(radius - distance + 0.5f, 0f, 1f);
                image[x, y] = new Rgba32(0x6F, 0xC0, 0x72, (byte) (alpha * 220));
            }
        }

        _chessDotTexture = Texture.LoadFromImage(image, "chess-dot");
        return _chessDotTexture;
    }

    /// <summary>
    /// Green ring used on squares that hold an enemy piece: the centre stays transparent so
    /// the piece itself remains readable while the capture target is still a green circle.
    /// </summary>
    private static Texture GetChessRingTexture()
    {
        if (_chessRingTexture != null)
            return _chessRingTexture;

        const int size = 16;
        var image = new SixLabors.ImageSharp.Image<Rgba32>(size, size);
        var center = (size - 1) / 2f;
        const float outer = size / 2f - 0.5f;
        const float inner = outer - 3f;

        for (var y = 0; y < size; y++)
        {
            for (var x = 0; x < size; x++)
            {
                var dx = x - center;
                var dy = y - center;
                var distance = MathF.Sqrt(dx * dx + dy * dy);
                var alpha = Math.Clamp(outer - distance + 0.5f, 0f, 1f) *
                            Math.Clamp(distance - inner + 0.5f, 0f, 1f);
                image[x, y] = new Rgba32(0x6F, 0xC0, 0x72, (byte) (alpha * 235));
            }
        }

        _chessRingTexture = Texture.LoadFromImage(image, "chess-ring");
        return _chessRingTexture;
    }

