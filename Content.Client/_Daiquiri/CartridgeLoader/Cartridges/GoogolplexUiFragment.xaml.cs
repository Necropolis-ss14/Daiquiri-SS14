    private bool IsChessLastMoveSquare(int index)
    {
        if (_chessLastMove.Length < 4)
            return false;

        return SquareToIndex(_chessLastMove[..2]) == index ||
               SquareToIndex(_chessLastMove.Substring(2, 2)) == index;
    }

    private static int SquareToIndex(string square)
    {
        if (square.Length != 2)
            return -1;

        var file = square[0] - 'a';
        var rank = square[1] - '1';
        if (file is < 0 or > 7 || rank is < 0 or > 7)
            return -1;

        return (7 - rank) * 8 + file;
    }

