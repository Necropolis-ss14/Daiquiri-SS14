        StarWaySubthreadTitle.Text = "";
        StarWaySubthreadStatus.Visible = false;
    }

    private void OnCreateSubthreadPressed(BaseButton.ButtonEventArgs args)
    {
        CreateSubthread();
    }

    private void CreateSubthread()
    {
        var title = StarWaySubthreadTitle.Text?.Trim();
        if (string.IsNullOrWhiteSpace(title) || string.IsNullOrEmpty(_currentStarWayBoardCode))
            return;

        // One subthread per hour. Keep the form open and spell out the remaining time
        // instead of dropping the action silently.
        var now = _timing.CurTime;
        if (now < _nextSubthreadAllowed)
        {
            ShowSubthreadCooldown();
            return;
        }

        _awaitingSubthread = true;
        var message = new StarWayUiMessageEvent(
            StarWayUiAction.CreateSubthread,
            _currentStarWayBoardCode,
            _currentStarWayThreadId,
            title: title);
        _boundUi?.SendMessage(new CartridgeUiMessage(message));

        _nextSubthreadAllowed = now + SubthreadCooldown;
        CloseSubthreadCreator();
    }

    private void ShowSubthreadCooldown()
    {
        var remaining = _nextSubthreadAllowed - _timing.CurTime;
        if (remaining <= TimeSpan.Zero)
        {
            StarWaySubthreadStatus.Visible = false;
            return;
        }

        StarWaySubthreadStatus.Visible = true;
        UpdateSubthreadCooldownText(remaining);

        var generation = ++_subthreadCooldownGeneration;
        Robust.Shared.Timing.Timer.Spawn(TimeSpan.FromMilliseconds(500), () => TickSubthreadCooldown(generation));
    }

    private void TickSubthreadCooldown(int generation)
    {
        if (generation != _subthreadCooldownGeneration)
            return;

        var remaining = _nextSubthreadAllowed - _timing.CurTime;
        if (remaining <= TimeSpan.Zero)
        {
            StarWaySubthreadStatus.Visible = false;
            return;
        }

        UpdateSubthreadCooldownText(remaining);
        Robust.Shared.Timing.Timer.Spawn(TimeSpan.FromMilliseconds(500), () => TickSubthreadCooldown(generation));
    }

    private void UpdateSubthreadCooldownText(TimeSpan remaining)
    {
        var total = (int)Math.Ceiling(remaining.TotalSeconds);
        StarWaySubthreadStatus.Text =
            $"Подтред раз в час. Осталось: {total / 60}:{total % 60:D2}";
    }

    private void AddStarWayPost(StarWayPostInfo postInfo)
    {
        var isAdmin = _adminManager.IsActive();

        var post = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 2,
            Margin = new Thickness(0, 0, 0, 10),
        };

        var header = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 6,
        };

        var headerText = $"{postInfo.Author} {postInfo.Timestamp} №{postInfo.Number:D6}";
        if (isAdmin && !string.IsNullOrEmpty(postInfo.RealAuthor) && postInfo.RealAuthor != postInfo.Author)
            headerText += $" · ник: {postInfo.RealAuthor}";

        header.AddChild(CreateWrappedText(headerText, Color.FromHex("#006600")));

        post.AddChild(header);

        // Admins get a trash button to the right of the message text.
        var body = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 6,
        };

        body.AddChild(CreateWrappedText(postInfo.Text, Color.Black));

        if (isAdmin)
        {
            var trash = new TextureButton
            {
                TextureNormal = _resourceCache.GetTexture("/Textures/_Daiquiri/Googolplex/trash_icon.png"),
                MinWidth = 20,
                MinHeight = 20,
                MaxWidth = 20,
                MaxHeight = 20,
                VerticalAlignment = VAlignment.Top,
                MouseFilter = MouseFilterMode.Stop,
            };

            var number = postInfo.Number;
            trash.OnPressed += _ => DeleteStarWayPost(number);
            body.AddChild(trash);
        }

        post.AddChild(body);

        StarWayContent.AddChild(post);
    }

    private void DeleteStarWayPost(int number)
