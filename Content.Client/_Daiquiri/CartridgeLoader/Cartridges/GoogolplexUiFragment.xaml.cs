        ShowChessGamePage();
    }

    private void StartChessChallenge()
    {
        if (ChessGameInProgress)
            return;

        if (!_chessLinkLinked || _chessLinkTokenExpired)
        {
            ShowChessFriendStatus("Сначала привяжите аккаунт Lichess.");
            return;
        }

        // A Lichess play ban only disables the public seek pool. Direct friend
        // challenges are still accepted by Lichess, so only a broken token stops them.
        if (_chessAccessBroken)
        {
            ShowChessFriendStatus(
                string.IsNullOrEmpty(_chessBlockReason)
                    ? "Lichess не принимает доступ к аккаунту. Привяжите аккаунт заново."
                    : _chessBlockReason);
            return;
        }

        var opponent = ChessFriendOpponentInput.Text.Trim();
        if (opponent.Length == 0)
        {
            ShowChessFriendStatus("Укажите ник соперника на Lichess.");
            return;
        }

        _chessGameSearching = true;
        ResetChessGameView(
            "created",
            $"Вызов отправлен игроку {opponent}. Ждём принятия...",
            $"{_chessFriendMinutes}+{_chessFriendIncrement}",
            _chessFriendMinutes);
        _chessAutoOpenedGameKey = "search";
        SendChessMessage(new ChessUiMessageEvent(
            ChessUiAction.StartChallenge,
            timeMinutes: _chessFriendMinutes,
            incrementSeconds: _chessFriendIncrement,
            opponent: opponent,
            color: _chessFriendColor,
            rated: _chessFriendRated));
        UpdateChessGamePanel();
        ShowChessGamePage();
    }

