    /// <summary>
    /// Transparent input layer over the board. Using one control for the whole board makes
    /// click-click and drag-and-drop share the same coordinate math, and the piece buttons
    /// stay purely decorative.
    /// </summary>
    private void SetupChessBoardInput()
    {
        if (_chessBoardInput != null)
            return;

        _chessBoardInput = new ChessBoardInputControl
        {
            // A plain Control measures to zero. Give the input layer the board's size so it
            // is always hit-testable even if the grid's measure changes.
            MinSize = new Vector2(ChessCellSize * 8, ChessCellSize * 8),
        };
        _chessBoardInput.PointerDown += OnChessBoardPointerDown;
        _chessBoardInput.PointerUp += OnChessBoardPointerUp;
        _chessBoardInput.PointerMove += OnChessBoardPointerMove;

        LayoutContainer.SetAnchorLeft(_chessBoardInput, 0f);
        LayoutContainer.SetAnchorTop(_chessBoardInput, 0f);
        LayoutContainer.SetAnchorRight(_chessBoardInput, 1f);
        LayoutContainer.SetAnchorBottom(_chessBoardInput, 1f);
        ChessBoardHost.AddChild(_chessBoardInput);

        // Fallback for the rare case where the transparent overlay is not the mouse
        // control (for example after a layout/style update). The grid then handles the
        // same clicks itself; the overlay handles them normally and stops propagation.
        ChessBoardGrid.MouseFilter = MouseFilterMode.Stop;
        ChessBoardGrid.OnKeyBindDown += args =>
        {
            if (args.Function != EngineKeyFunctions.UIClick)
                return;

            OnChessBoardPointerDown(args.PointerLocation);
            args.Handle();
        };
        ChessBoardGrid.OnKeyBindUp += args =>
        {
            if (args.Function != EngineKeyFunctions.UIClick)
                return;

            OnChessBoardPointerUp(args.PointerLocation);
            args.Handle();
        };

        _chessDragPiece = new TextureRect
        {
            Visible = false,
            MinSize = new Vector2(ChessCellSize, ChessCellSize),
            CanShrink = true,
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            MouseFilter = MouseFilterMode.Ignore,
        };
        LayoutContainer.SetAnchorLeft(_chessDragPiece, 0f);
        LayoutContainer.SetAnchorTop(_chessDragPiece, 0f);
        LayoutContainer.SetAnchorRight(_chessDragPiece, 0f);
        LayoutContainer.SetAnchorBottom(_chessDragPiece, 0f);
        LayoutContainer.SetMarginRight(_chessDragPiece, ChessCellSize);
        LayoutContainer.SetMarginBottom(_chessDragPiece, ChessCellSize);
        ChessBoardHost.AddChild(_chessDragPiece);
    }

