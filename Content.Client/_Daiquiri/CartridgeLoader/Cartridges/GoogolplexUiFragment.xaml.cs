    private static string? FindStarWayBoardCode(string segment)
    {
        foreach (var board in StarWayBoards)
        {
            if (string.Equals(board.Code, segment, StringComparison.OrdinalIgnoreCase))
                return board.Code;
        }

        return null;
    }

