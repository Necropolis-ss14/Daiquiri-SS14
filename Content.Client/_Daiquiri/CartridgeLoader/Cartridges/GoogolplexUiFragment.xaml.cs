    /// <summary>
    /// Called by the server when the thread state is updated.
    /// </summary>
    public void OnStarWayStateReceived(StarWayUiState state)
    {
        if (state.BoardCode != _currentStarWayBoardCode)
            return;

        // A freshly created subthread arrives as a state whose parent is the thread we were
        // looking at; adopt it so the creator lands inside the new subthread.
        if (state.ThreadId != _currentStarWayThreadId)
        {
            if (!_awaitingSubthread || state.ParentThreadId != _currentStarWayThreadId)
                return;

            _awaitingSubthread = false;
        }

        RefreshThread(state);
    }

    private void RefreshThread(StarWayUiState state)
    {
        _currentStarWayThreadId = state.ThreadId;
        _currentStarWayParentId = state.ParentThreadId;
        _awaitingSubthread = false;

        SetAddress($"starway.nt/t/{state.BoardCode.ToLowerInvariant()}{(state.ThreadId > 0 ? "/" + state.ThreadId : "/")}");

        StarWayContent.RemoveAllChildren();

        var parentId = state.ParentThreadId;
        var boardCode = state.BoardCode;
        var back = CreateStarWayLink(
            parentId < 0 ? "Назад к доскам" : "Назад в тред",
            () =>
            {
                if (parentId < 0)
                    BuildStarWayIndex();
                else
                    OpenStarWayThread(boardCode, parentId);
            });
        back.Margin = new Thickness(0, 30, 0, 8);
        StarWayContent.AddChild(back);

        var titleText = CreateWrappedText(state.ThreadTitle, Color.Black, _pixelFont);
        titleText.Margin = new Thickness(0, 0, 0, 6);
        StarWayContent.AddChild(titleText);

        var description = CreateWrappedText(state.ThreadDescription, Color.FromHex("#5A4A1A"));
        description.Margin = new Thickness(0, 0, 0, 8);
        StarWayContent.AddChild(description);

        if (state.Subthreads.Count > 0)
        {
            StarWayContent.AddChild(new Label
            {
                Text = "Подтреды:",
                FontOverride = _smallPixelFont,
                FontColorOverride = Color.FromHex("#5A4A1A"),
                HorizontalAlignment = HAlignment.Left,
                Margin = new Thickness(0, 2, 0, 2),
            });

            foreach (var subthread in state.Subthreads)
            {
                var id = subthread.Id;
                var link = CreateStarWayLink($"{subthread.Title} ({subthread.PostCount})",
                    () => OpenStarWayThread(boardCode, id));
                link.Margin = new Thickness(0, 0, 0, 2);
                StarWayContent.AddChild(link);
            }
        }

        // Only board roots can spawn subthreads: no sub-subthreads.
        if (state.ThreadId == 0)
        {
            var create = CreateStarWayLink("+ Создать подтред", OpenSubthreadCreator);
            create.Margin = new Thickness(0, 6, 0, 10);
            StarWayContent.AddChild(create);
        }

        foreach (var post in state.Posts)
            AddStarWayPost(post);

        StarWayContent.AddChild(CreateWrappedText(">> Тред открыт. Оставляйте ответы вежливо.",
            Color.FromHex("#0000CC")));

        StarWayScroll.VScrollTarget = float.MaxValue;
    }

