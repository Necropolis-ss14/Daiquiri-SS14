    private int PositionToDisplay(Vector2 position)
    {
        var size = ChessBoardGrid.Size;
        var cellWidth = size.X > 0 ? size.X / 8f : ChessCellSize;
        var cellHeight = size.Y > 0 ? size.Y / 8f : ChessCellSize;

        var col = (int) MathF.Floor(position.X / cellWidth);
        var row = (int) MathF.Floor(position.Y / cellHeight);
        if (col is < 0 or > 7 || row is < 0 or > 7)
            return -1;

        return row * 8 + col;
    }

