        _chessUnlimited = state.Unlimited;
        _chessCastling = state.Castling ?? string.Empty;
        _chessEnPassant = state.EnPassant ?? string.Empty;
        _chessChallengeId = state.ChallengeId ?? string.Empty;
        _chessChallenger = state.ChallengerName ?? string.Empty;
        _chessChallengeTimeControl = state.ChallengeTimeControl ?? string.Empty;
        _chessChallengeRated = state.ChallengeRated;
        _chessChallengeColor = string.IsNullOrEmpty(state.ChallengeColor) ? "random" : state.ChallengeColor;

        // A seek or a challenge is not a game yet. Force the start position even if a
        // delayed snapshot from the previous match still carries its board or opponent.
        var searchingWithoutGame = state.Searching && string.IsNullOrEmpty(state.GameId);
        if (searchingWithoutGame || (!state.InGame && !state.Searching))
        {
            _chessBoard = ChessStartBoard;
            _chessTurn = "white";
            _chessMyColor = string.Empty;
            _chessOpponent = string.Empty;
            _chessLastMove = string.Empty;
            _chessCastling = "KQkq";
            _chessEnPassant = string.Empty;
        }
        else if (state.Board.Length == 64)
        {
            _chessBoard = state.Board;
        }
        else
        {
            _chessBoard = ChessStartBoard;
        }

        // The shared rules engine uses the same board layout as the snapshot, so the
        // client can highlight exactly the moves Lichess will accept.
        _chessPosition = ChessPosition.FromState(_chessBoard, _chessTurn, _chessCastling, _chessEnPassant);

        var sameGame = !string.IsNullOrEmpty(state.GameId) &&
                       string.Equals(previousGameId, state.GameId, StringComparison.Ordinal);
        var boardChanged = !string.Equals(previousBoard, _chessBoard, StringComparison.Ordinal);

        if (sameGame &&
            boardChanged &&
            state.LastMove.Length >= 4 &&
            !string.Equals(previousLastMove, state.LastMove, StringComparison.Ordinal))
        {
            PlayChessMoveSound(previousBoard, state.LastMove, state.Status);
        }

        if (!sameGame && state.InGame && !state.Searching && state.LastMove.Length == 0)
        {
            _chessAudio.PlayGlobal(
                new SoundPathSpecifier("/Audio/Effects/Arcade/newgame.ogg"),
                Filter.Local(),
                false,
                AudioParams.Default.WithVolume(-5f));
        }

        _chessSelectedIndex = -1;
        _chessLegalMoves.Clear();
        _chessDragging = false;
        _chessDragWasSelected = false;
        _chessDragFrom = -1;
        HideChessDragPiece();

        var errorText = state.Error;
        var hasError = !string.IsNullOrEmpty(errorText) &&
                       !string.Equals(errorText, state.StatusText, StringComparison.Ordinal);

        // The final snapshot is sent before the server forgets the game. A later idle
        // snapshot (for example after reopening the PDA) returns to the lobby.
        if (!state.InGame && !state.Searching && ChessGamePage.Visible)
        {
            ShowChessLobbyPage();

            // ShowChessLobbyPage hides the status line, so report the failure afterwards,
            // otherwise a rejected seek silently drops the player back into the lobby.
            if (hasError)
                ShowChessStatus(errorText, true);

            // The snapshot may also carry an incoming challenge, so refresh the lobby
            // widgets before leaving: the challenge panel lives on the lobby page.
            UpdateChessGamePanel();
            return;
        }

        if (hasError)
            ShowChessStatus(errorText, true);

        var finished = IsChessFinishedStatus(_chessGameStatus);
        var inProgress = _chessGameSearching || (_chessGameActive && !finished);

        if (!inProgress)
        {
            _chessGamePageDismissed = false;
            _chessAutoOpenedGameKey = string.Empty;
        }

        UpdateChessGamePanel();
        ResetChessClocks(state.WhiteTimeMs, state.BlackTimeMs);
        UpdateChessPlayPanel();
        RenderChessBoard();

        if (finished &&
            !IsChessFinishedStatus(previousStatus) &&
            wasActive &&
            sameGame &&
            wasGamePageVisible)
        {
            ShowChessResultPopup(state);
        }

        if (!inProgress || _chessGamePageDismissed)
            return;

        // Do not yank the player away from another site if a game finishes or starts in
        // the background. Only the chess site itself auto-opens the game subsite.
        if (!ChessPage.Visible && !ChessGamePage.Visible && !ChessFriendPage.Visible && !ChessBotPage.Visible)
            return;

        var key = _chessGameId.Length > 0 ? _chessGameId : "search";
        if (key == _chessAutoOpenedGameKey)
            return;

        _chessAutoOpenedGameKey = key;
        ShowChessGamePage();
    }

