using System.Numerics;
using Content.Shared._Daiquiri.AIHelp;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Network;
using Robust.Shared.Utility;
using static Content.Shared._Daiquiri.AIHelp.SharedAIHelpSystem;

namespace Content.Client._Daiquiri.AIHelp.UI;

[GenerateTypedNameReferences]
public sealed partial class AIHelpAdminWindow : DefaultWindow
{
    public event Action? OnRefresh = delegate { };
    public event Action<int>? OnCancelRequest = delegate { };
    public event Action<NetUserId>? OnClearContext = delegate { };
    public event Action<NetUserId, bool>? OnSetMuted = delegate { };

    private readonly List<AIHelpRequestLogEntry> _entries = new();
    private readonly HashSet<NetUserId> _muted = new();
    private int _selectedIndex = -1;

    public AIHelpAdminWindow()
    {
        RobustXamlLoader.Load(this);

        MinSize = new Vector2(780, 520);

        RefreshButton.OnPressed += _ => OnRefresh.Invoke();
        CancelButton.OnPressed += _ => WithSelected(entry => OnCancelRequest.Invoke(entry.Id));
        ClearContextButton.OnPressed += _ => WithSelected(entry => OnClearContext.Invoke(entry.UserId));
        MuteButton.OnPressed += _ => WithSelected(entry => OnSetMuted.Invoke(entry.UserId, true));
        UnmuteButton.OnPressed += _ => WithSelected(entry => OnSetMuted.Invoke(entry.UserId, false));

        RequestList.OnItemSelected += args =>
        {
            _selectedIndex = args.ItemIndex;
            ShowSelected();
        };
    }

    public void UpdateLog(List<AIHelpRequestLogEntry> entries, List<NetUserId> muted)
    {
        _entries.Clear();
        _entries.AddRange(entries);

        _muted.Clear();
        foreach (var id in muted)
            _muted.Add(id);

        var previous = _selectedIndex;
        RequestList.Clear();

        foreach (var entry in _entries)
        {
            var status = Loc.GetString(StatusKey(entry.Status));
            var mark = _muted.Contains(entry.UserId) ? " [X]" : string.Empty;
            RequestList.AddItem($"{entry.Time}  {entry.PlayerName}{mark}  [{status}]  {Shorten(entry.Text, 60)}");
        }

        _selectedIndex = previous >= 0 && previous < _entries.Count ? previous : _entries.Count - 1;
        if (_selectedIndex >= 0)
            RequestList[_selectedIndex].Selected = true;

        ShowSelected();
    }

    private void WithSelected(Action<AIHelpRequestLogEntry> action)
    {
        if (_selectedIndex < 0 || _selectedIndex >= _entries.Count)
            return;

        action(_entries[_selectedIndex]);
    }

    private void ShowSelected()
    {
        Details.Clear();

        if (_selectedIndex < 0 || _selectedIndex >= _entries.Count)
            return;

        var entry = _entries[_selectedIndex];
        var status = Loc.GetString(StatusKey(entry.Status));

        Details.AddMessage(FormattedMessage.FromUnformatted($"{entry.PlayerName}  {entry.Time}  [{status}]"));

        if (_muted.Contains(entry.UserId))
            Details.AddMessage(FormattedMessage.FromUnformatted(Loc.GetString("ai-help-admin-blocked-mark")));

        Details.AddMessage(FormattedMessage.FromUnformatted(Loc.GetString("ai-help-admin-prompt")));
        Details.AddMessage(FormattedMessage.FromUnformatted(entry.Text));
        Details.AddMessage(FormattedMessage.FromUnformatted(Loc.GetString("ai-help-admin-reply")));
        Details.AddMessage(FormattedMessage.FromUnformatted(string.IsNullOrEmpty(entry.Reply) ? "-" : entry.Reply));

        if (entry.Tokens > 0)
            Details.AddMessage(FormattedMessage.FromUnformatted($"{Loc.GetString("ai-help-admin-tokens")}: {entry.Tokens}"));
    }

    private static string StatusKey(AIHelpRequestStatus status) => status switch
    {
        AIHelpRequestStatus.Pending => "ai-help-admin-status-pending",
        AIHelpRequestStatus.Answered => "ai-help-admin-status-answered",
        AIHelpRequestStatus.Cancelled => "ai-help-admin-status-cancelled",
        AIHelpRequestStatus.Blocked => "ai-help-admin-status-blocked",
        _ => "ai-help-admin-status-failed",
    };

    private static string Shorten(string text, int max)
        => text.Length <= max ? text : text[..max] + "...";
}
