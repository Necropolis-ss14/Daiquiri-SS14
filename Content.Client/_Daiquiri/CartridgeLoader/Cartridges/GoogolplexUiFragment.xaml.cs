        if (remaining <= TimeSpan.Zero)
        {
            StarWaySubthreadStatus.Visible = false;
            return;
        }

        UpdateSubthreadCooldownText(remaining);
        Robust.Shared.Timing.Timer.Spawn(TimeSpan.FromMilliseconds(500), () => TickSubthreadCooldown(generation));
    }

