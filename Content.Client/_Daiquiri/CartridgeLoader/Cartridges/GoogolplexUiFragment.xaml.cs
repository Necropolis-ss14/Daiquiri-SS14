    /// <summary>
    /// Browser-style navigation from the address bar. Known virtual URLs open the matching
    /// page; anything else is treated as a Googolplex query.
    /// </summary>
    private void NavigateTo(string raw, string notFoundMessage = "Сайт не найден")
    {
        var text = raw.Trim();
        var lower = text.ToLowerInvariant();

        if (lower.StartsWith("https://"))
        {
            text = text[8..];
            lower = lower[8..];
        }
        else if (lower.StartsWith("http://"))
        {
            text = text[7..];
            lower = lower[7..];
        }

        var cut = lower.IndexOfAny(new[] { '?', '#' });
        if (cut >= 0)
        {
            text = text[..cut];
            lower = lower[..cut];
        }

        while (lower.EndsWith('/'))
        {
            text = text[..^1];
            lower = lower[..^1];
        }

        switch (lower)
        {
            case "googolplex.nt":
            case "googolplex.nt/search":
                ShowSearchPage();
                return;
            case "googolplex.nt/sites":
                ShowSitesPage();
                return;
            case "starway.nt":
                ShowStarWayPage();
                return;
        }

        const string searchPrefix = "googolplex.nt/search/";
        if (lower.StartsWith(searchPrefix))
        {
            var query = text[searchPrefix.Length..].Trim();
            ShowSearchPage();
            if (query.Length > 0)
            {
                SearchBox.Text = query;
                ShowResultsPage(query);
            }

            return;
        }

        const string threadPrefix = "starway.nt/t/";
        if (lower.StartsWith(threadPrefix))
        {
            var rest = text[threadPrefix.Length..];
            var parts = rest.Split('/', StringSplitOptions.RemoveEmptyEntries);
            var code = parts.Length > 0 ? FindStarWayBoardCode(parts[0]) : null;
            if (code != null)
            {
                var threadId = 0;
                if (parts.Length > 1)
                    int.TryParse(parts[1], out threadId);

                ShowStarWayPage();
                OpenStarWayThread(code, threadId);
                return;
            }
        }

        // Unknown address: full-screen error page.
        ShowErrorPage(text, notFoundMessage);
    }

