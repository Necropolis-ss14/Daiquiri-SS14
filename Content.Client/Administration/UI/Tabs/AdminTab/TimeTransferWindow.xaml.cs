using Content.Client.Administration.UI.CustomControls;
using Content.Shared.Administration;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Administration.UI.Tabs.AdminTab;

[GenerateTypedNameReferences]
public sealed partial class TimeTransferWindow : DefaultWindow
{
    [Dependency] private IClientConsoleHost _console = default!;

    public TimeTransferWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        PlayerList.OnSelectionChanged += OnPlayerSelected;
        UsernameLine.OnTextChanged += _ =>
        {
            StatusLabel.Text = string.Empty;
            UpdateButton();
        };
        TransferButton.OnPressed += _ => Transfer();

        UpdateButton();
    }

    private void OnPlayerSelected(PlayerInfo? player)
    {
        UsernameLine.Text = player?.Username ?? string.Empty;
        StatusLabel.Text = string.Empty;
        UpdateButton();
    }

    private void UpdateButton()
    {
        TransferButton.Disabled = string.IsNullOrWhiteSpace(UsernameLine.Text);
    }

    private void Transfer()
    {
        var username = UsernameLine.Text.Trim();
        if (string.IsNullOrEmpty(username))
            return;

        var flags = string.Empty;
        if (IncludeCommandCheckBox.Pressed)
            flags += " --command";
        if (IncludeSecurityCheckBox.Pressed)
            flags += " --security";

        _console.ExecuteCommand($"playtime_unlockall \"{username}\"{flags}");
        StatusLabel.Text = Loc.GetString("time-transfer-window-sent", ("username", username));
    }
}
