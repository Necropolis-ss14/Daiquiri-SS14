using Content.Client.UserInterface.Controls;
using Content.Shared._Daiquiri.PaperPlease;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Daiquiri.PaperPlease;

[GenerateTypedNameReferences]
public sealed partial class PassportGuideWindow : FancyWindow
{
    private PassportGuideUiState? _state;
    private int _tab;

    public PassportGuideWindow()
    {
        RobustXamlLoader.Load(this);

        ContentPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#f4efe2"),
            BorderColor = Color.FromHex("#00000044"),
            BorderThickness = new Thickness(1),
        };

        YearButton.OnPressed += _ => Select(0);
        ConventionButton.OnPressed += _ => Select(1);
        StatesButton.OnPressed += _ => Select(2);
        RulesButton.OnPressed += _ => Select(3);
    }

    public void Update(PassportGuideUiState state)
    {
        _state = state;
        Select(_tab);
    }

    private void Select(int tab)
    {
        _tab = tab;
        if (_state is null)
            return;

        Content.Text = tab switch
        {
            0 => _state.Year,
            1 => _state.Convention,
            2 => _state.States,
            _ => _state.Rules,
        };
        Content.ModulateSelfOverride = Color.FromHex("#111111");
    }
}
